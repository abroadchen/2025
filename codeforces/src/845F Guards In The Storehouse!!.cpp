/**
str[][]：存网格，'x' 表示障碍（不能放置/不能经过）。
f[d][S][k]：滚动数组 DP 状态：
d 取 0/1，滚动两行（当前格奇偶）；
S 是轮廓线状态，二进制位表示当前处理到这格的轮廓线上各位置的状态（插头/砖块的边界连接情况）；
第三维 [2] 表示一个额外标志（例如当前行是否已经有一个"开始/括号匹配插头"、或是否处于某种特殊状态）。
msk：状态掩码，限制 S 的最大二进制位
读入网格。若 n < m（列多于行），就把矩阵转置，使得 n ≥ m。
目的是让较窄的维度作为状态宽度 m，从而缩小轮廓线状态 S 的位数（状态大小与 m 直接相关），降低 DP 复杂度
轮廓线有 m+1 条边/接口，所以掩码 msk 保留 m+1 位。
初始状态：f[0][0][0] = 1，DP 起点为空状态，方案数为 1
到达格子 (i,j)，切换到当前滚动层 d。
状态 S 里，第 x=j 位和第 y=j+1 位对应当前格子上方和左方的插头/连接状态：p = 上插头, q = 左插头。
T 是把这两位从 S 中"取走/清零"后的中间状态。
v0、v1 是上一层同状态的两种标志的方案数
分支 1：当前格是障碍 'x'
障碍格：不能放置任何东西，因此必须上下、左左插头都是 0（不能有插头进入障碍格）。这里直接把状态 T（两个插头被清除）沿原样继承，两个标志都照传。若 p 或 q 非 0 实际应无解，这里代码直接继承，说明障碍格要求 p=q=0 的约束靠上层不产生进入障碍格的转移来保证。
分支 2：普通空格，放置连接
情况 (2a)：在两个插头位置 x、y 都放上插头（T | (1<<x) | (1<<y)），p=q=0 → p'=q'=1。这通常对应"在该格放一条拐弯连接（比如下右都伸出）"。
这里把 v0 传向 ini 状态标志 0、v1 传向标志 1
分支 3：直线贯通或起点
情况 (2b)（p 或 q 至少一个非 0）：做一次直线贯通——把左插头移到上、把上插头移到左（T | (q<<x) | (p<<y)），即交换这两位，形成直走。
情况 (2c)（p==q==0）：这是"从该格开始一段新连接"的起点，走 else 分支：add(f[d][T][1], v0)——从上一层的 v0（标志 0）产生本层标志 1（表示已进入一段连接状态）。这也解释了为什么需要第三维 [2]：用来记录"当前格是否新开了一段待配对的连接"。
这种 p,q → 交换/置位/标志翻转 的转移，正是轮廓线插头 DP 的典型写法，用于统计把网格连接成若干段"匹配对"的方案数（两端插头互相配对）。
每处理完一整行后，做一次"换行位移"：把轮廓线状态 S 左移 1 位（(S<<1) & msk），逻辑上把上一行最右边的插头/边界信息平移到下一行的起点。两个标志 0/1 都随行滚动
处理完全部格子后，把最后一层所有状态 S 的两种标志方案数全部累加到 ans，输出。
注意：这里把标志 0 和标志 1 都计入，意味着允许有一对未闭合的连接存在（例如允许恰好一条从"起点"连到终点的开放配对），这是该题统计对象的具体设定——通常对应"某些允许开放的连接方案数"
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int mod = 1e9+7;
inline void add(int& x, int y) {
    x += y;
    if (x >= mod) x -= mod;
}

int n, m, msk, f[2][(1<<16)+1][2], ans;
char str[255][255];
int main() {
    fast;
    cin >> n >> m;
    int i, j, d = 0, S, T, x, y, p, q, v0, v1;
    for (i = 0; i < n; ++i) cin >> str[i];
    if (n < m) {
        for (i = 0; i < n; ++i)
            for (j = i; j < m; ++j) swap(str[i][j], str[j][i]);
        swap(n, m);
    }
    msk = (1<<(m+1))-1, f[0][0][0] = 1;
    for (i = 0; i < n; ++i) {
        for (j = 0; j < m; ++j) {
            d ^= 1, memset(f[d], 0, sizeof(f[d]));
            for (S = 0; S <= msk; ++S) {
                x = j, y = j+1, p = (S>>x)&1, q = (S>>y)&1, T = S^(p<<x)^(q<<y),
                v0 = f[d^1][S][0], v1 = f[d^1][S][1];
                if (!v0 && !v1) continue;
                if (str[i][j] == 'x') {
                    add(f[d][T][0], v0), add(f[d][T][1], v1);
                    continue;
                }
                add(f[d][T|(1<<x)|(1<<y)][0], v0), add(f[d][T|(1<<x)|(1<<y)][1], v1);
                if (p || q) add(f[d][T|(q<<x)|(p<<y)][0], v0), add(f[d][T|(q<<x)|(p<<y)][1], v1);
                else add(f[d][T][1], v0);
            }
        }
        d ^= 1, memset(f[d], 0, sizeof(f[d]));
        for (S = 0; S <= msk; ++S)
            add(f[d][(S<<1)&msk][0], f[d^1][S][0]), add(f[d][(S<<1)&msk][1], f[d^1][S][1]);
    }
    for (S = 0; S <= msk; ++S) add(ans, f[d][S][0]), add(ans, f[d][S][1]);
    cout << ans;
    return 0;
}