/**
用二分/分治方式求 floor(log2(n))（即 n 的最高有效位的下标）。
每行：若右移若干位后仍非 0，则累加对应位权并右移。最终 m = n 的最高位位置。
功能等价于 63 - __builtin_clzll(n)，但手写 inline
读操作类型 x 和第一个参数 y。
类型 1：y = get(y) → 把 y 变成它的最高位下标；读 z；b1[y] -= z。→ 在 b1 的该位上累加 -z（一种"减法/下移"标记）。

类型 2：类似，b2[y] += z（"加法/上移"标记）。

类型 3（最长）：进行一系列位级计算并输出多个整数，核心是用 b1[p]、b2[p] 作为偏移量 t，对 y 做"环形折返加偏移"
p = floor(log2 y)，y 的最高位下标
z = 2^p，即最高位 p 的位权
s = 2^(p+1) - 1，即"最高位为 p"的这一层的最大可能值
取 -b1[p]（b1 在该层的取反偏移量）。
与 (z-1)（即 2^p - 1，一个 p 位全 1 的掩码）做按位与。
作用：从 b1 中取出该层偏移，取负并截断到 p 位宽（即对 z-1 取"mod 叠加"效应）。由于 -b1[p] 若为负数，按位与得到的可能是"补码截断"，所以下一行还要再修正
如果上一步得到的 t 是负数，就加一次 z，再与 (z-1) 按位与，强制落到 [0, z) 范围内的非负偏移。
作用：把可能为负的偏移量换算成 [0, 2^p-1] 内的非负 t。(注意：long long 与、运算结果是带符号的，负数的 & 高位会补 1，所以需要这一步规整。)
更新候补值：x = 当前 y + 该层偏移 t。
这是"环形加法"的第一步：先做加法。
若加法结果超出本层上界 s：
x & s：保留 x 处于本层内的低位部分（模 s+1）。
再加 z：折返到本层的起点（最低值 2^p）‍。
作用：当偏移导致越界时，把结果"折回"到本层段内，实现环形循环
把修正后的 x 赋值给 y，进入后续层级的处理。
作用：将结果作为下一次计算的输入
只要 p 仍 > 0（还有更低的位要处理），就继续循环。
作用：从最高位 p 一路往下处理到最低位（每一轮 p 减 1）
更新本层上界：s = 2*z - 1 = 2^(p+1)-1。
与开头一致，重算当前 p 对应层的上界。（其实与第 2 行相同，但进入循环后 z 会变化，故重算。）
取 b2[p]，与 (z-1) 按位与，得到本层 p 的偏移量 t（截断到 p 位宽）。
注意这里用的是 b2（不是 b1），且没有取负
同上，把可能为负的 t 规整到 [0, z-1] 非负区间
候选值 = 当前 y + 偏移 t（b2 方向）
越界则折返到本层起点（环形处理，同第 6 行）
更新 y 为修正后的值，继续用 y 进入下一步（更低层）
p 减 1，即从"当前处理的层"下移到"低一位的层"。
这一行标志着向下移动一层
这三步完成层间下降的准备工作：
上界 s 更新为新层范围。
位权 z 减半（对应 p 已减 1）。
y 右移 1 位，即"丢掉刚处理完的最高位，继续处理低一层"。
这三行是"从高层递归/递降到低层"的关键：z 减半、y 右移
取 b1[p]（注意：此时 p 已经 --p 过，指向新的（更低的）层）与 (z-1) 按位与，取该层 b1 偏移量 t
规整负 t 到非负区间（同前）
候选值 = y（已右移）+ b1 偏移
越界折返（同前）
注意这里先备份再输出再恢复：输出的是"该层修正后的 x"，但 y 本身仍保留为原来的值（因为外层还需要它继续下降处理更低层）。
这三行的作用是：输出当前层的运算结果，同时保留未更新的 y 供下一层继续使用（用临时变量 yf 保存/恢复）
 */
#include <bits/stdc++.h>
#define ll long long
using namespace std;

constexpr int N = 70;

inline int get(ll n) {
    int m = 0;
    if (n>>32) m |= 32, n >>= 32;
    if (n>>16) m |= 16, n >>= 16;
    if (n>>8) m |= 8, n >>= 8;
    if (n>>4) m |= 4, n >>= 4;
    if (n>>2) m |= 2, n >>= 2;
    if (n>>1) m |= 1, n >>= 1;
    return m;
}

template<class T>
void rd(T& x) {
    int f = 0, ch = 0; x = 0;
    for (; !isdigit(ch); ch = getchar()) if (ch == '-') f = 1;
    for (; isdigit(ch); ch = getchar()) x = (x<<1)+(x<<3)+(ch&15);
    if (f) x = -x;
}
template<class T>
void write(T x) {
    if (x < 0) { putchar('-'); x = -x; }
    T y = 1;
    int len = 1;
    for (; y <= x/10; y *= 10) ++len;
    for (; len; --len, x %= y, y /= 10) putchar(x/y+48);
}

int T, p;
ll x, y, z, s, t, yf, b1[N], b2[N];
int main() {
    rd(T);
    while (T--) {
        rd(x), rd(y);
        if (x == 1) y = get(y), rd(z), b1[y] -= z;
        else if (x == 2) y = get(y), rd(z), b2[y] += z;
        else {
            write(y), putchar(' ');
            p = get(y); z = 1ll<<p; s = (z<<1)-1; t = -b1[p]&(z-1);
            if (t < 0) t = (t+z)&(z-1);
            x = y + t;
            if (x > s) x = (x&s) + z;
            y = x;
            while (p > 0) {
                s = (z<<1) - 1;
                t = b2[p]&(z-1);
                if (t < 0) t = (t+z)&(z-1);
                x = y + t;
                if (x > s) x = (x&s) + z;
                y = x;
                --p;
                s = z-1; z = z>>1; y = y>>1; t = b1[p]&(z-1);
                if (t < 0) t = (t+z)&(z-1);
                x = y + t;
                if (x > s) x = (x&s) + z;
                yf = y; y = x;
                write(y), putchar(' '), y = yf;
            }
            putchar('\n');
        }
    }
    return 0;
}