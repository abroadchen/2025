/**
n：左括号（也是右括号）的对数，序列总长 2n。
k：要构造的是字典序第 k 个合法括号序列（从 1 或 0 计数，见下文）。
s：结果字符串，构造中逐步追加。
st：全局栈深度，即"已经放置但仍未闭合的左括号数量"
外层 for i = 1..n

语义上，每轮尝试放置一个左括号的"时机"。
循环体内先用 while 处理"应放右括号"的情况，最后必放一个左括号（s += '('; st++）。所以 n 次循环 = 放置 n 个左括号。
内层 while (k < (st+1)*st/2)

这是关键判断。分析这一条件：

st 是当前未闭合的左括号数。
若我现在放右括号，会形成一个什么局面？当前这串右括号之后还能构造的排列数……
(st+1)*st/2 是组合数 C(st+1, 2) 的写法，即 (st+1)*st/2。
这个量对应的是：若当前这一步选择放右括号，后续（从"放这个右括号"的动作开始）还有多少种合法补全方式。
具体地，C(st+1, 2) 的直觉：当前栈深 st，若放一个右括号（栈深变 st−1），后面还剩下的合法完成方案数恰好是 C(st+1, 2)——这是一类括号序列结构计数的已知结论（与"括号记忆"、卡塔兰格局限下的计数有关）。

条件 k < (st+1)*st/2 表示：排在目标 k 之前的排列数足够大，使得我"不放左括号、改放右括号"时，仍能覆盖到第 k 个。
若成立 → 说明第 k 个解在"这一步放右括号"的分支里，所以我们放右括号。
若不成立（k >= 该数）→ 说明第 k 个解落在"这一步放左括号"分支，放左括号。

s += ')'：放一个右括号。
st--：栈深减 1（闭合一个左括号）。
k -= st：因为这一步"跳过了" st 种排列（放右括号前，这个右括号会与当前栈里的 st 个左括号之一配对，产生 st 种不同情况），所以 k 减去 st，等价于 在这 st 种情况之外继续找第 k 个。
这里 k -= st（减去新的 st），与二项式/计数结构对应。
循环条件是 k < (st+1)*st/2，每次放右括号后 st 变小、(st+1)*st/2 变小，直到不满足条件，跳出 while
while 结束表示条件不再满足（即 k >= (st+1)*st/2），此时第 k 个落在"放左括号"分支，故放 '('，栈深 st++。
这一轮就完成了。
综合：这个 while+必放左括号的模式，本质是在做字典序贪心——每一步根据当前栈深与剩余计数 k 的关系，决定放 ( 还是 )，从而一步步"定位"到第 k 个排列。
循环处理后，还有 st 个左括号未闭合，末尾补上对应个数的 )，使序列合法。
每次 st--、k -= st 更新 k。
若收尾后 k 仍不为 0，说明实际排列数不足 k 个（k 太大），输出 Impossible。
否则输出构造好的第 k 个合法括号序列 s。
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define int long long
using namespace std;

int st;
signed main() {
    fast;
    int n, k; cin >> n >> k;
    string s;
    for (int i = 1; i <= n; ++i) {
        while (k < (st+1)*st/2) s += ')', st--, k -= st;
        s += '(', st++;
    }
    while (st) s += ')', st--, k -= st;
    if (k) cout << "Impossible\n"; else cout << s;
    return 0;
}