/**
网格的大小 N = 305 ，表示我们用一个 305 × 305 的方格来模拟路径。
为什么选 305？因为每步最多走一定距离，n 步下来坐标绝对值不会超过 150，所以用中心 (150, 150) 作为起点后，
坐标范围在 [0, 300] 内，留一点余量就是 305
第 1 维 0~304 当前横坐标 x
第 2 维 0~304 当前纵坐标 y
第 3 维 0~29 当前正在执行第几步 dep （最多 30 步）
第 4 维 0~7 当前朝向 dir （8 个方向）

- 类型是 bool ，占 1 字节，总大小约 305 × 305 × 30 × 8 ≈ 22MB ，在栈上放不下，必须是 全局变量 （全局变量放在静态存储区而非栈上）。
- 作用： 记忆化搜索 ，如果 DFS 已经在位置 (x,y) 、第 dep 步、朝向 dir 这个状态搜索过了，直接返回，避免指数级爆炸
n int 步数（最多 30）
a[40] int[40] 每一步走的格子数 a[i] （下标 1~n，最多 30 步）
nx[8] int[8] 8 个方向的横坐标增量 ny[8] int[8] 8 个方向的纵坐标增量
vis[N][N] bool[N][N] 路径覆盖标记数组 ， vis[x][y]=1 表示格子 (x,y) 被至少一条路径经过
// dir=0: 上     (0, 1)    → nx[0]=0,   ny[0]=1
// dir=1: 左上   (-1, 1)   → nx[1]=-1,  ny[1]=1
// dir=2: 左     (-1, 0)   → nx[2]=-1,  ny[2]=0  ← 初始方向
// dir=3: 左下   (-1, -1)  → nx[3]=-1,  ny[3]=-1
// dir=4: 下     (0, -1)   → nx[4]=0,   ny[4]=-1
// dir=5: 右下   (1, -1)   → nx[5]=1,   ny[5]=-1
// dir=6: 右     (1, 0)    → nx[6]=1,   ny[6]=0
// dir=7: 右上   (1, 1)    → nx[7]=1,   ny[7]=1
- 左转 ： (dir + 7) % 8 （逆时针旋转 45°，比如从"上"变成"右上"）
- 右转 ： (dir + 1) % 8 （顺时针旋转 45°，比如从"上"变成"左上"）

- x, y ：当前所在格子的坐标。
- dir ：当前朝向（0~7，对应上面的 8 个方向）。
- dep ：当前正在执行第几步（从 1 到 n）

- dep > n ：所有 n 步都执行完了，到达终点，返回。
- mp[x][y][dep][dir] ： 这个状态已经访问过了 （记忆化剪枝），直接返回，避免重复搜索

沿着当前方向 dir ，一步一步地走 a[dep] 格：
- x += nx[dir]; y += ny[dir] ：每走一格，坐标按方向增量更新。
- vis[x][y] = 1 ： 标记这个格子被路径覆盖 （不只是起点终点，中间经过的每一格都要标记）

读入步数 n （最多 30）
循环读入 n 步的每步长度 a[1] ~ a[n] （第 i 步走 a[i] 格）
- x=150, y=150 ： 起点坐标 （网格的中心，保证所有路径都在 [0, 300] 范围内，不越界）。
- dir=2 ： 初始朝向 为 dir=2，即 向左 （ nx[2]=-1, ny[2]=0 ）。
- dep=1 ：从第 1 步开始执行
- int ans = 0 ：覆盖格子计数器。
- 双重循环遍历整个网格 ：从 (0,0) 到 (300, 300) （ N-5=300 ，留 5 格余量避免越界）。
- if (vis[i][j]) ans++ ：如果格子 (i,j) 被至少一条路径覆盖，计数加 1
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 305;
bool mp[N][N][30][8];
int n, a[40], nx[] = {0, -1, -1, -1, 0, 1, 1, 1}, ny[] = {1, 1, 0, -1, -1, -1, 0, 1}, vis[N][N];
void dfs(int x, int y, int dir, int dep) {
    if (dep > n || mp[x][y][dep][dir]) return;
    //把当前 (x, y, dep, dir) 标记为已访问，后续再遇到就直接 return
    mp[x][y][dep][dir] = true;
    for (int i = 1; i <= a[dep]; ++i) {
        x += nx[dir]; y += ny[dir];
        vis[x][y] = 1;
    }
    dfs(x, y, (dir+1)%8, dep+1);
    dfs(x, y, (dir+7)%8, dep+1);//等价于 (dir - 1 + 8) % 8
}


int main() {
    fast;
    cin >> n;
    memset(mp, 0, sizeof(mp)); memset(vis, 0, sizeof(vis));
    for (int i = 1; i <= n; ++i) cin >> a[i];
    dfs(150, 150, 2, 1);
    int ans = 0;
    for (int i = 0; i <= N-5; ++i)
        for (int j = 0; j <= N-5; ++j)
            if (vis[i][j]) ans++;
    cout << ans << '\n';
    return 0;
}