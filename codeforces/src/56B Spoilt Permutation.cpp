/*
 *声明并初始化两个整数l和r为-1，用于记录需要调整的区间的左右边界
 *
*循环读取数组元素并查找第一个和最后一个不在正确位置的元素：

从1到n读取数组元素存储在a[i]中
如果当前位置i的值不等于i（即a[i] != i），说明该元素位置不正确
如果l还是初始值-1，说明这是第一个位置不正确的元素，将l设为i
更新r为当前位置i，这样r始终指向最后一个位置不正确的元素
 *如果l仍然小于0，说明所有元素都在正确位置（数组已经有序），输出"0 0"并结束程序
 *
*检查从l到r这个区间内的元素是否构成一个反转序列：

对于区间[l,r]内的每个位置i，检查a[i]是否等于l+r-i
这个公式表示在反转序列中，原位置i的元素应该放到位置(l+r-i)
如果有任何元素不满足这个条件，说明这个区间不是简单的反转，输出"0 0"并结束程序
 *
 *如果通过了所有检查，说明区间[l,r]是一个需要反转的最小区间，输出这个区间的左右边界，然后返回0结束程序
 *
 */
#include <cstdio>
#include <vector>
using namespace std;

int main() {


    int n; scanf("%d",&n);
    vector<int> a(n + 1);
    int l(-1), r(-1);

    for (int i = 1; i <= n; ++i) {
        scanf("%d",&a[i]);
        if (i != a[i]) {
            if (l < 0) l = i;
            r = i;
        }
    }
    if (l < 0) { puts("0 0"); return 0; }
    for (int i = l; i <= r; ++i) {
        if (a[i] != l + r - i) {
            puts("0 0");
            return 0;
        }
    }
    printf("%d %d\n",l, r);
    return 0;
}