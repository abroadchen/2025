/*
*条件1：(y/a) % 2 == 0（y所在的层数是偶数层）
条件2：y > (y/a) * a（y坐标大于该层的起始位置）
条件3：-a < x < 0（x坐标在左半部分）
编号：3 * (y/a) / 2（根据层数计算区域编号）
 *
*条件1-2：同上（偶数层且在层内）
条件3：0 < x < a（x坐标在右半部分）
编号：3 * (y/a) / 2 + 1（右半部分编号加1）
 *
*条件1：(y/a) % 2 == 1（y所在的层数是奇数层）
条件2：y > (y/a) * a（在层内）
条件3：-a < 2*x < a（即 -a/2 < x < a/2，中间区域）
编号：(3 * (y/a) + 1) / 2
 *
 *
*层0 (y ∈ [0,a)):     层1 (y ∈ [a,2a)):    层2 (y ∈ [2a,3a)):
   ┌─────┐               ┌─────┐              ┌─────┐
   │  1  │              │  2  │             │  4  │
   └─────┘               └─────┘              └─────┘

层3 (y ∈ [3a,4a)):    层4 (y ∈ [4a,5a)):   层5 (y ∈ [5a,6a)):
  ┌───┬───┬───┐          ┌─────┐            ┌───┬───┬───┐
  │ 5 │ 6 │ 7 │         │  8  │           │ 9 │10 │11 │
  └───┴───┴───┘          └─────┘            └───┴───┴───┘

  偶数层: 3个区域        奇数层: 1个区域      偶数层: 3个区域
 */
#include <cstdio>
using namespace std;

int a, x, y;

int main() {
    scanf("%d %d %d", &a, &x, &y);
    int ans(-1);
    if (y > 0 && y < a) {
        if (-a < 2 * x && 2 * x < a) ans = 1;//判断点是否在底部第一个菱形区域内
    } else if ((y / a) % 2 == 0 && y > (y / a) * a && -a < x && x < 0) {
        ans = 3 * (y / a) / 2;
    } else if ((y / a) % 2 == 0 && y > (y / a) * a && x > 0 && x < a) {
        ans = 3 * (y / a) / 2 + 1;
    } else if ((y / a) % 2 == 1 && y > (y / a) * a && -a < 2 * x && 2 * x < a) {
        ans = (3 * (y / a) + 1) / 2;
    }
    printf("%d\n", ans);
    return 0;
}