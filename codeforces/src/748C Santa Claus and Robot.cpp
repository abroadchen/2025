/**
若只有一次移动（ n==1 ），路径本身就是一段，无需分割，直接输出 1 并结束程序
- ans = 0 ： 分割次数计数器 ，初始为0。每发生一次方向反转（从正到负或反之），加1。
- dx = 0 ： 水平方向状态 ：
- dx > 0 ：当前水平移动方向为右（ R ）。
- dx < 0 ：当前水平移动方向为左（ L ）。
- dx = 0 ：当前无水平移动（或刚切换）。
- dy = 0 ： 垂直方向状态 ：
- dy > 0 ：当前垂直移动方向为上（ U ）。
- dy < 0 ：当前垂直移动方向为下（ D ）。
- dy = 0 ：当前无垂直移动（或刚切换）

- 遍历移动字符串 s 的每个字符 i 。 处理 U (上)移动
- 条件 dy >= 0 ：当前垂直方向为正（ dy>0 ，已经是上移）或未开始（ dy=0 ）。
  - 若为正（ dy>0 ）：继续上移，保持当前状态，无需分割。
  - 若为0（初始或刚切换）：设置 dy=1 ，开始上移。
- 否则（ dy < 0 ） ：当前垂直方向为负（正在下移）， 发生方向反转 ：
  - ++ans ：分割次数加1（因为从下移切换到上移，需要分割）。
  - dy = 1 ：设置新的垂直方向为上移。
  - dx = 0 ： 重置水平方向 （因为切换垂直方向时，水平方向需要重新开始，下一个水平移动会成为新段的开始）。 处理 D (下)移动
- 条件 dy <= 0 ：当前垂直方向为负（ dy<0 ，已经是下移）或未开始（ dy=0 ）。
  - 若为负（ dy<0 ）：继续下移，保持当前状态，无需分割。
  - 若为0（初始或刚切换）：设置 dy=-1 ，开始下移。
- 否则（ dy > 0 ） ：当前垂直方向为正（正在上移）， 发生方向反转 ：
  - ++ans ：分割次数加1。
  - dy = -1 ：设置新的垂直方向为下移。
  - dx = 0 ：重置水平方向。
处理 L (左)移动
- 条件 dx <= 0 ：当前水平方向为负（ dx<0 ，已经是左移）或未开始（ dx=0 ）。
  - 若为负：继续左移，保持当前状态。
  - 若为0：设置 dx=-1 ，开始左移。
- 否则（ dx > 0 ） ：当前水平方向为正（正在右移）， 发生方向反转 ：
  - ++ans ：分割次数加1。
  - dx = -1 ：设置新的水平方向为左移。
  - dy = 0 ： 重置垂直方向 （因为切换水平方向时，垂直方向需要重新开始）。 处理 R (右)移动
- 条件 dx >= 0 ：当前水平方向为正（ dx>0 ，已经是右移）或未开始（ dx=0 ）。
  - 若为正：继续右移，保持当前状态。
  - 若为0：设置 dx=1 ，开始右移。
- 否则（ dx < 0 ） ：当前水平方向为负（正在左移）， 发生方向反转 ：
  - ++ans ：分割次数加1。
  - dx = 1 ：设置新的水平方向为右移。
  - dy = 0 ：重置垂直方向
- ++ans ： 最终段数 = 分割次数 + 1 。
- 若分割了 k 次，则路径被分为 k+1 段。
- 例如：分割1次 → 2段；分割2次 → 3段。
- cout << ans << '\n' ：输出最少段数
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;

int n;
int main() {
    fast;
    string s; cin >> n >> s;
    if (1 == n) { cout << "1\n"; return 0; }
    int ans = 0, dx = 0, dy = 0;
    for (const char i : s) {
        if (i == 'U') {
            if (dy >= 0) dy = 1;
            else ++ans, dy = 1, dx = 0;
        } else if (i == 'D') {
            if (dy <= 0) dy = -1;
            else ++ans, dy = -1, dx = 0;
        } else if (i == 'L') {
            if (dx <= 0) dx = -1;
            else ++ans, dx = -1, dy = 0;
        } else {
            if (dx >= 0) dx = 1;
            else ++ans, dx = 1, dy = 0;
        }
    }
    ++ans;
    cout << ans << '\n';
    return 0;
}