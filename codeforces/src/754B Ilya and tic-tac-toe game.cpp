/**
10×10 的棋盘数组 。虽然题目只有 4×4，但开 10×10 足够容纳方向偏移（最大 ±2），避免越界
四组方向数组 ，每组都是 9 个元素（索引 0~8）。其中索引 0 是原地（(0,0)），没用。 实际方向是索引 1~8 共 8 个方向 。
dx/dy[i] 跳到对面第 3 个位置 （隔 1 格） 距离 2
nx/ny[i] 跳到中间位置 距离 1
1 ↓ 正下 (0, 2) (0, 1) 当前→中→远 连成竖线
2 → 正右 (2, 0) (1, 0) 横向三连
3 ↑ 正上 (0, -2) (0, -1) 向上三连
4 ← 正左 (-2, 0) (-1, 0) 向左三连
5 ↘ 右下 (2, -2) (1, -1) 右下斜向三连
6 ↗ 右上 (2, 2) (1, 1) 右上斜向三连
7 ↖ 左上 (-2, 2) (-1, 1) 左上斜向三连
8 ↙ 左下 (-2, -2) (-1, -1) 左下斜向三连
命中标记 ： flag=true 表示已经找到可以形成三连的情况，后续直接输出 YES。

从棋盘位置 (x, y) 出发，检查 8 个方向。
情况 A：两端是 'x'，中间不是 'o'
- 远位置 （隔 2 格）是 'x' 。
- 中间位置 （隔 1 格） 不是 'o' （中间可以是 'x' 或 '.' ）。
- 含义：当前是 'x' ，对面也是 'x' ，中间没有被对方 'o' 阻挡 → 这条线可以形成三连 。
情况 B：中间是 'x'，远位置是 '.'
- 远位置 是空位 '.' 。
- 中间位置 是 'x' 。
- 含义：当前是 'x' ，中间也是 'x' ，远处是空位 → 两个 'x' 相邻，差一步就能三连 。

读入 4×4 棋盘。用嵌套循环，每行 4 个字符（用空格分隔， cin 会跳过空白）。
两层循环 遍历整个棋盘：
- 如果当前位置是 'x' → 调 dfs(i, j) 检查它的 8 个方向。
- 一旦 flag=true （找到可以三连的情况）→ 立即输出 YES 并 return 0 结束， 不再继续遍历 （提前退出是性能优化）。
所有 'x' 位置都检查完了， flag 还是 false → 棋盘上不存在能形成三连的情况，输出 NO 。
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;

char a[10][10];
int dx[] = {0, 0, 2, 0, -2, 2, 2, -2, -2}, dy[] = {0, 2, 0, -2, 0, -2, 2, 2, -2},
nx[] = {0, 0, 1, 0, -1, 1, 1, -1, -1}, ny[] = {0, 1, 0, -1, 0, -1, 1, 1, -1};
bool flag = false;

void dfs(int x, int y) {
    for (int i = 1; i <= 8; ++i) {
        if (a[x+dx[i]][y+dy[i]] == 'x' && a[x+nx[i]][y+ny[i]] != 'o') { flag = true; return; }
        if (a[x+dx[i]][y+dy[i]] == '.' && a[x+nx[i]][y+ny[i]] == 'x') { flag = true; return; }
    }
}

int main() {
    fast;
    for (int i = 1; i <= 4; ++i)
        for (int j = 1; j <= 4; ++j) cin >> a[i][j];
    for (int i = 1; i <= 4; ++i)
        for (int j = 1; j <= 4; ++j) {
            if (a[i][j] == 'x') dfs(i, j);
            if (flag == true) { cout << "YES"; return 0; }
        }
    cout << "NO";
    return 0;
}