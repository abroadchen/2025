/*
*将m重新计算为2*m - 2
这通常表示网格的周期长度（例如在蛇形网格中）
*n减1，然后判断是否仍大于等于0
控制循环执行n次
 *起始位置s、最终位置f、时间t
 *
*s ^ f 是按位异或运算
如果s和f不同（异或结果非零），执行前面的表达式
如果s和f相同（异或结果为零），直接输出t
 *
 *在周期性结构（如蛇形网格）中计算位置的转换
 *
*如果s > f：使用m + 2 - s
否则：使用s
整个表达式计算某种周期性偏移
 *
*如果s > f：使用m + 2 - f
否则：使用f
最后减1
 *
*在一个周期性结构中计算移动时间
考虑正向和反向移动的不同情况
 */
#include <cstdio>
using namespace std;

int main() {
    int n, m, s, f, t; scanf("%d%d", &n, &m);
    for (m = m * 2 - 2; n--;
        printf("%d\n", s ^ f ?
            (t + m - (s > f ? m + 2 - s : s)) / m * m +
            (s > f ? m + 2 - f : f) - 1 : t))
        scanf("%d%d%d", &s, &f, &t);
    return 0;
}