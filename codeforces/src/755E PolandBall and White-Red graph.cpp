/**
n 图的节点数
k 目标度数（希望 恰好一个 顶点度数 = k）
k == 1 要 恰好一个 顶点度数 = 1。但树中 叶子节点都是度数 1 ，只要有一个叶子，必然有至少两个叶子。无法满足"恰好一个度数为 1"。
k >= 4 要 恰好一个 顶点度数 ≥ 4。但 n 个节点的图中，度数为 k 的顶点最多有 n-1 条边，这限制了它的邻居的度数...
实际上更核心的原因是：构造度数 ≥ 4 且恰好一个顶点满足的图很难通过简单树实现。
n <= 3 节点太少了，无法构造出"恰好一个度数为 k"的图。n=1 无边，n=2 两个顶点度数都是 1，n=3 要么是链（度数 1,2,1）
要么三角形（度数都是 2），都不可能恰好一个度数为 k（k≠其他）。

n=4, k=2 无解
n=4 节点的图：
- 树必须是 3 条边
- 树的度数序列总和 = 2×3 = 6，4 个节点
- 树至少有 2 个叶子（度数 1）
- 要 恰好一个 顶点度数 = 2
可能的树（形状都同构）：
1 — 2 — 3 — 4     (链)
  度数: 1, 2, 2, 1  ← 两个度数 2，不满足"恰好一个"

  以 2 为中心的星形？不行，度数会是 3
  三角形 + 一条边？有环，不是树

k=2 且 n ≥ 5 —— 链
第一行: n-1  (边数)
接下来 n-1 行: 每条边的两个端点

k=3 —— 星形变种

1 n - 2 （连接 3~n，共 n-2 个顶点）
2 1（只连 n） n 2（连 1 和 2）
3 ~ n-1 1（只连 1）
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;


int main() {
    fast;
    int n, k; cin >> n >> k;
    if (k == 1 || k >= 4 || n <= 3) { puts("-1"); return 0; }
    if (k == 2) {
        if (n == 4) { puts("-1"); return 0; }
        cout << n - 1 << '\n';
        for (int i = 1; i < n; ++i)
            cout << i << ' ' << i + 1 << '\n';
    } else {
        cout << n - 1 << '\n' << "2 " << n << '\n';
        for (int i = 3; i <= n; ++i)
            cout << "1 " << i << '\n';
    }
    return 0;
}