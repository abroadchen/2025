/**
c[3][3] ll[3][3] 组合数表 （C(n,k)，n≤2），用于 DP 转移时做"从 n 个位置选 k 个"的计数
f[55][110][2] ll[55][110][2] 三维 DP 表 ，核心状态存储
a[55] int[55] 存储某个数的 二进制位 （ a[i] 是第 i 位的值，0 或 1 或 2）
整数 s （上界，所有计数都要求节点数 ≤ s）
C(n,k) n=0 n=1 n=2
k=0 1 1 1
k=1 — 1 2
k=2 — — 1
- C(n,0) = 1：从 n 个里选 0 个，只有 1 种方案。
- C(n,n) = 1：从 n 个里选 n 个，只有 1 种方案。
- C(2,1) = 2：从 2 个里选 1 个，有 2 种方案。
这个表很小（只用到 n ≤ 2），因为后面 DP 中"可选择的位置数"最多就是 2
- l rs = 0 ：最终答案计数器，初始为 0。
- f[51][0][0] = 1 ：DP 边界初始化。
- f[51][0][0] = 1 ：表示 处理完所有二进制位（到第 51 位）、已用节点数=0、状态=0 有 1 种方案。
- 这是 DP 的 终止边界 ，后面倒序转移

对每个可能的树高 h ，判断存在多少种 节点数 ≤ s 的单棵满二叉树方案
- 遍历所有可能的树高 h 。
- (1ll<<(h+1))-1 ：满二叉树节点总数公式 2^(h+1) - 1 （高度 h 的满二叉树有这么多节点）。
- 只考虑节点总数 ≤ s 的 h
- 取模运算： s 除以满二叉树节点数的 余数 。
- 含义：如果用满二叉树的节点数做"周期"， t 是 s 中"剩余的零头"
- 贪心扣减 ：从大到小尝试扣减满二叉树的节点数。
- (1ll<<i)-1 ：另一棵满二叉树的节点数（高度 i-1 的）。
- 如果 t 足够大，就扣一个。
- 判断条件 ：扣减后 t == 0 ，说明 s 恰好可以被若干棵满二叉树的节点数 无剩余地表示 （类似于二进制，但用满二叉树节点数做基底）。
- 满足条件 → rs++ ，方案数加 1
- h1 ：第一棵树的高度。
- h2 ：第二棵树的高度。
- 外层和内层的循环条件都是 拼接后总节点数 ≤ s
两棵满二叉树的节点数相加， 减去重叠部分 （拼接时共用一些节点）
- t 取模后的余数（类似第一部分的逻辑，调整了公式）。
- 如果 t == 0 ，说明直接合法， rs++ 并跳过当前 h1,h2 对的 DP 计算
- t >> i & 1 ：取 t 的第 i 位二进制的值（0 或 1）。
- 存入 a[i] 数组，共 50 位（ ll 最大约 2^63，50 位够用）
- n 从 1 到 h1 + h2 - 2 。
- 这个 n 可以理解为 二进制加法进位时的溢出位置数
- a[p]&2 ：检查当前位是否 ≥ 2（发生了进位溢出）。
- a[p] ^= 2 ：位上减去 2（等价于 a[p] -= 2 ，但用位运算更快）。
- a[p+1]++ ：进位到更高位。
- p ：记录进位发生的最高位置
当 n == 1 时，强制把 p 设为 50（跳过所有低位的 DP 转移，直接让高位发挥作用）。这是题目逻辑的一个特殊分支
从进位最高位 p 开始， 倒序 DP 转移 （从高位到低位）。
- memset(f[i], 0, sizeof*f) ：清空当前层 f[i][*][*] 的值，准备重新计算
- j ： 已用节点数 ，从 0 到 h1+h2-2 。
- o ： 状态位 ，0 或 1（通常表示上一位加法的进位）。
- if (f[i+1][j][o]) ：只遍历有值的状态（剪枝）
- k ：在第 i 位放置的"某种标记"的数量。
- (i<h1)+(i<h2) ： 最多可选位置数 。如果当前位在两个树的高度范围内各算 1，就有 2 个可选位置（上限 2，对应之前 c[3][3] 的 3×3 表）。
- j + k <= h1+h2-2 ：节点总数不超过上限
- o << 1 ：上一位的进位 o 左移一位（进到当前位的高位）。
- | (a[i]&1) ：当前位的二进制值 a[i] 的最低位（0 或 1）。
- 组合起来： o << 1 | (a[i]&1) 是 当前位需要达到的目标值 （0、1、或 2）。
- 减去 k （当前位置的贡献）得到 w ： 新的进位
- 合法状态检查 ：进位 w 只能是 0 或 1（二进制加法的进位不可能超过 1）。
- 转移 ：
- 新状态： f[i][j+k][w] （当前位 i，已用 j+k 个节点，新进位 w）。
- 旧状态贡献： f[i+1][j][o] （上一位 i+1，已用 j 个节点，旧进位 o）。
- 乘以组合数 ： c[(i<h1)+(i<h2)][k] （从可选位置中选 k 个的方案数）
- ~a[0]&1 ：检查 a[0] 的最低位是否为 0（等价于 a[0] % 2 == 0 ）。
- 如果条件满足， rs 加上 f[1][n][0] ：
- 表示 所有位都处理完 （从高位到第 1 位）、用了 n 个节点、最终进位为 0 的方案数。
- 最终进位必须是 0（没有溢出到第 0 位之外）才算合法
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

ll c[3][3], f[55][110][2];
int a[55];
int main() {
    fast;
    ll s; cin >> s;
    c[0][0] = c[1][0] = c[1][1] = c[2][0] = c[2][2] = 1; c[2][1] = 2;
    ll rs = 0; f[51][0][0] = 1;
    for (int h = 0; (1ll<<(h+1))-1 <= s; ++h) {
        ll t = s % ((1ll<<(h+1))-1);
        for (int i = h; i; --i)
            if (t >= (1ll<<i)-1) t -= (1ll<<i)-1;
        if (!t) rs++;
    }
    for (int h1 = 1; (1ll<<(h1+1))-1 <= s; ++h1)
        for (int h2 = 1; (1ll<<(h1+1))+(1ll<<(h2+1))+(1ll<<h2)-4 <= s; ++h2) {
            ll t = (s - (1ll<<h2) + 1) % ((1ll<<(h1+1))+(1ll<<(h2+1))-3);
            if (!t) { rs++; continue; }
            for (int i = 0; i < 50; ++i) a[i] = t >> i & 1;
            for (int n = 1; n <= h1 + h2 - 2; ++n) {
                int p = 0; a[0]++;
                for (; a[p]&2; ++p) { a[p] ^= 2; a[p+1]++; }
                if (n == 1) p = 50;
                for (int i = p; i; --i) {
                    memset(f[i], 0, sizeof*f);
                    for (int j = 0; j <= h1+h2-2; ++j)
                        for (int o = 0; o < 2; ++o) if (f[i+1][j][o]) {
                            for (int k = 0; k <= (i<h1)+(i<h2) && j + k <= h1+h2-2; ++k) {
                                int w = (o<<1 | (a[i]&1)) - k;
                                if (w == 0 || w == 1)
                                    f[i][j+k][w] += f[i+1][j][o]*c[(i<h1)+(i<h2)][k];
                            }
                        }
                }
                if (~a[0]&1) rs += f[1][n][0];
            }
        }
    cout << rs << '\n';
    return 0;
}