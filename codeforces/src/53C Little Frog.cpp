/*
 *
 *\n在格式字符串中会消耗输入中的换行符
*x初始化为1（递增序列的起始值）
y初始化为n（递减序列的起始值）
 *
*如果i是偶数（包括0）：
打印x的当前值，后面跟一个空格
然后将x自增1（后缀递增）
*如果i是奇数：
打印y的当前值，后面跟一个空格
然后将y自减1（后缀递减）

当n=5时：

i=0(偶数): 输出x=1，x变为2
i=1(奇数): 输出y=5，y变为4
i=2(偶数): 输出x=2，x变为3
i=3(奇数): 输出y=4，y变为3
i=4(偶数): 输出x=3，x变为4
输出结果：1 5 2 4 3
当n=6时：

输出结果：1 6 2 5 3 4
特点：

生成的序列是1到n的所有数字的一个排列
交替从序列的两端取值：最小值、最大值、次小值、次大值...
这种模式常用于生成"波动"序列或实现特定的排序模式


 */
#include <cstdio>
using namespace std;

int main() {

    long n; scanf("%ld\n",&n);
    long x(1), y(n);
    for (long i = 0; i < n; ++i) {
        if (i % 2 == 0) printf("%ld ", x++);
        else printf("%ld ", y--);
    }
    puts("");//输出一个换行符（puts会自动添加换行符）
    return 0;
}