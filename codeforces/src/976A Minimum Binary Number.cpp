/**
n：总位数。
cnt[2]：统计数组，cnt[0] 记录数字 0 的个数，cnt[1] 记录数字 1 的个数。
t：临时变量，存放每次读入的一位数字
%1d 表示每次只读入一个字符并当成数字（一次读一位），读入 0 或 1 到 t。
cnt[t]++：按 t 的值累加对应计数（t 为 0 则 cnt[0]++，为 1 则 cnt[1]++）
① 至少有一个 1（cnt[1] 非零）
首位放 1：保证不以 0 开头、且值最小（非零首位最小为 1）。

随后把全部 0依次输出，这样除首位外其他位尽可能小（全是 0）。

因为只需要一个 1 打头，其余任何 1 都不再输出（多出的 1 会被丢弃，但放在后面比 0 大，不走最小）。其他多余的 1 怎么办？ —— 为了让数最小，多余的 1 必须放在最末尾。而这里循环里 cnt[1] 只在 if 判断用了一次，多余的 1 应当在最后补上才完整。但这段代码只输出一个 '1' 和所有 '0'，没有在最后补上剩余的 1。

关键点：若 cnt[1] 超过 1（有两个以上 1），这段代码会丢弃多余的 1——它只输出一个 1 和所有 0。典型完整解应是"1 + 全部0 (cnt[0] 个) + 剩余(cnt[1]-1)个1"。这里存在漏掉多余 1 的问题（除非题意保证最多只有一个 1）。
② 没有 1（cnt[1]==0，全是 0）
直接输出 0（所有位都是 0，最小表示为一个 0）
 */
#include <bits/stdc++.h>
using namespace std;

int n, cnt[2], t;
int main() {
    scanf("%d", &n);
    for (int i = 0; i < n; i++) scanf("%1d", &t), cnt[t]++;
    if (cnt[1]) {
        putchar('1');
        while (cnt[0]--) putchar('0');
        putchar('\n');
    } else puts("0");
    return 0;
}