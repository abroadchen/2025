/**
deg：正 n 边形每个内角 = 180*(n-2)/n。

注意：三角形取顶点 1,2,3。由于正多边形，顶点 1,2,3 构成的三角形中，在顶点 2 处的内角是 (180 - deg)/2。为什么？因为顶点 2 的内角被多边形内角"切掉"一部分——实际上顶点 2 是三角形的一个角，其值 = 正 n 边形内角被弦切开后的一半，即 (180-deg)/2。（几何上：以顶点 2 为顶点的那个三角形角，= (180 - 内角)/2。）

ans 初始为 3：默认选顶点 1,2,3
枚举第 i 个顶点作为三角形第三个顶点（始终固定 1 和 2）。
顶点 1, 2, i 构成三角形，顶点 2 处的内角为 t = (180 - deg) * (i-2) / 2。
若 t 比当前最佳 ang 更接近目标 a，则更新 ang 和 ans。
最终输出 2 1 ans：固定 2 和 1，第三个顶点是使角度最接近 a 的 ans

在正 n 边形中，顶点 1, 2, i 形成的角，其顶点在位置 2、3、… 的度数是随顶点间隔线性变化的：
顶点 2 到顶点 i 相隔 (i-2) 条边，对应圆心角为 (i-2) * 360/n... 但代码用的是内角表达式 (180-deg) * (i-2)/2。
因为 180 - deg = 360/n（已验证：180 - 180(n-2)/n = 180*2/n = 360/n），所以 t = (360/n) * (i-2)/2 = 180*(i-2)/n。
所以其实 t = 180*(i-2)/n，这就是顶点 2 处的三角形内角（弦 1-i 与弦 2-i 夹角引出的角）。随着 i 增大，t 线性增大，所以可以线性逼近任意角度
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;


int main() {
    fast;
    int n, a;
    while (cin >> n >> a) {
        double deg = 180.0*(n-2)/n, ang = (180-deg)/2, t;
        int ans = 3;
        for (int i = 4; i <= n; ++i) {
            t = (180.0-deg)*(i-2)/2;
            if (abs(ang-a) > abs(t-a)) {
                ang = t;
                ans = i;
            }
        }
        cout << "2 1 " << ans << '\n';
    }
    return 0;
}