/**
定义字符数组 a，从下标 1 开始存放字符串（注意不是从 0）。
scanf("%s", a+1) 读入一个字符串存入 a[1] 起的地址。比如输入 1210，则 a[1]='1', a[2]='2', a[3]='1', a[4]='0'
l：字符串长度（从 a+1 数起），例如 1210 的 l=4。
i=1 指向开头。
j 初始为 l（末尾），循环向前跳过所有 '0'，直到 j 指向一个非 '0' 字符或 j<1。
例：1210 → j 从 4 开始，a[4]=='0'，j 减到 3（a[3]='1' 非 0，停止）。即 j=3。
再如 1000 → j 从 4 跳到 1，a[1]='1' 非 0，j=1。
若全是 0，如 0000，j 会减到 0。
作用：忽略数字末尾的 0。因为回文判断时末尾的 0 会破坏对称性，题目意图是"若该数字去掉末尾 0 后是回文则 YES"
双指针 i（从左）、j（从右）向中间扫描。
一旦 a[i] != a[j] 就输出 NO 并结束。
全部相等则输出 YES
 */
#include <bits/stdc++.h>
using namespace std;

char a[15];
int main() {
    scanf("%s", a+1);
    int l = strlen(a+1), i = 1, j;
    for (j = l; j >= 1 && a[j] == '0'; --j) {}
    for (; i <= j; ++i, --j)
        if (a[i] != a[j]) {
            printf("NO");
            return 0;
        }
    printf("YES");
    return 0;
}