/*
*n: 参数（可能表示级别或深度） 曲线的迭代级别
d: 输入的数字（用于解码）一维距离值（0到4^n-1）
x, y: 输出坐标，初始化为0
 *
*循环从 i = 2*n-2 开始，每次减少2，直到 i >= 0
r: 临时变量用于存储中间计算结果
v: 状态变量，初始化为0
 *
*计算 r：
4 * v: 将v左移2位
(d >> i) & 3: 取d的第i和i+1位（2位二进制数，值为0-3）
|: 按位或操作
*更新x和y坐标：
x << 1: x左移1位（相当于乘以2）
(0x936c >> r) & 1: 从常量0x936c中提取第r位
|: 将提取的位添加到x的最低位
对y执行类似操作，但使用不同的常量0x39c6
*更新状态v：
从常量0x3e6b94c1中提取与2*r相关的2位
用于下一次迭代的状态计算
 *
*将d按2位一组分解
使用预计算的查找表确定每一步的坐标变化
通过状态机跟踪当前所在象限
*0x936c: x坐标变化查找表
0x39c6: y坐标变化查找表
0x3e6b94c1: 状态转换查找表
 */
#include <iostream>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;


int main() {
    fast;
    int n, d, x = 0, y = 0; cin >> n >> d;
    for (int i = 2 * n - 2, r, v = 0; i >= 0; i -= 2) {
        r = 4 * v | (d >> i) & 3;
        x = (x << 1) | (0x936c >> r) & 1;
        y = (y << 1) | (0x39c6 >> r) & 1;
        v = (0x3e6b94c1 >> 2 * r) & 3;
    }
    cout << x << ' ' << y;
    return 0;
}