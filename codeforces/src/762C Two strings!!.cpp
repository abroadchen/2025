/**
N = 1e6+5：数组上限，用于存储最多 10^6 长度的字符串。
inf = 0x3f3f3f3f：一个足够大的整数（约 1e9），常用于初始化极大值。
s[N], p[N]：分别存放主串和模式串的字符数组。
n, m：分别是 s 和 p 的长度。
nxt[26][N]：右侧最近出现表。nxt[c][i] 表示从位置 i 开始往右，第一个字符为 c 的下标。如果不存在，则为 n+1。
pre[26][N]：左侧最近出现表。pre[c][i] 表示从位置 i 开始往左，第一个字符为 c 的下标。如果不存在，则为 0。
L[N]：记录模式串 p 前缀每个字符在 s 中匹配成功后的最小下标。
R[N]：记录模式串 p 后缀每个字符在 s 中匹配成功后的最大下标

初始化哨兵值：对于任意字符 c，在 s 的末尾之后（即 n+1、n+2）都视为不存在，设为 n+1
倒序遍历：从右往左填充 nxt。
如果当前位置就是字符 c，则 nxt[c][i] = i。
否则继承右侧最近出现的位置 nxt[c][i+1]
正序遍历：从左往右填充 pre。
如果当前位置就是字符 c，则 pre[c][i] = i。
否则继承左侧最近出现的位置 pre[c][i-1]
使用 nxt 和 pre 快速定位模式串 p 在主串 s 中的最左/最右匹配位置
L[1]：模式串第一个字符 p[1] 在 s 中第一次出现的位置（从左往右搜索）
递推求解：L[i] 是模式串前 i 个字符在 s 中按顺序匹配成功后，最后一个字符所在的下标。
从 L[i-1]+1 开始往右找下一个字符 p[i] 的位置
R[m]：模式串最后一个字符 p[m] 在 s 中最后一次出现的位置（从右往左搜索）
递推求解：R[i] 是模式串从 i 到 m 的后缀，在 s 中按逆序匹配成功后，首字符所在的下标。
从 R[i+1]-1 开始往左找前一个字符 p[i] 的位置

ans：当前找到的最长子序列长度。
pr：后缀起始位置（在 p 中）。
pl：前缀结束位置（在 p 中
后缀最长匹配：从后往前遍历 R，找到能够匹配的最长后缀。
if (R[i]) 检查是否存在合法匹配（非零）。
更新 ans 为后缀长度 m-i+1，并记录起始下标 pr = i
恢复字符：之前将 p 转为了数字索引，这里加回 'a' 恢复成字符形式
如果整个模式串 p 本身就是一个有效的子序列（即能完整匹配），直接输出 p 并结束程序
设置哨兵：R[m+1] 设为无穷大，防止后续循环越界或比较错误

尝试将模式串分割为 [前缀][后缀] 两部分，使得它们在主串中的位置不冲突且总长度最长
now 初始化为后缀起始位置 pr（即当前已知的最长后缀起点）。
遍历 i 作为前缀结尾位置（从左往右扩展前缀）
检查当前后缀起始位置 now 是否与前缀结尾 i 冲突。
条件 R[now] <= L[i] 意味着后缀的起始位置（在 s 中）已经位于前缀结束位置左侧，二者重叠。
若冲突，++now 将后缀起始位置向右移动，直到找到一个不冲突的位置
如果前缀无法继续匹配（L[i] 超出了主串范围），提前退出循环
当前组合长度 = 前缀长度 i + 后缀长度 (m - now + 1)。
如果这个组合比之前记录的更长，则更新 ans 并记录新的前缀结尾 pl = i 和后缀起始 pr = now
如果最终没有找到任何有效的子序列（即 ans == 0），输出 "-" 表示失败
首先打印前缀 p[1..pl]。
然后打印后缀 p[pr..m]。
中间可能会有一段被省略（未匹配）的字符，这是允许的，因为我们只需要保证前缀和后缀各自匹配且不冲突
 */
#include <bits/stdc++.h>
using namespace std;

constexpr int N = 1e6+5, inf = 0x3f3f3f3f;
char s[N], p[N];
int n, m, nxt[26][N], pre[26][N], L[N], R[N];
int main() {
    scanf("%s%s", s+1, p+1);
    n = strlen(s+1), m = strlen(p+1);
    for (int i = 1; i <= n; ++i) s[i] -= 'a';//将字符转换为数字索引（'a' -> 0, 'b' -> 1, ...）
    for (int i = 1; i <= m; ++i) p[i] -= 'a';
    for (int c = 0; c <= 25; ++c) {
        nxt[c][n+1] = nxt[c][n+2] = n+1;
        for (int i = n; i >= 1; --i) {
            if (s[i] == c) nxt[c][i] = i;
            else nxt[c][i] = nxt[c][i+1];
        }
        for (int i = 1; i <= n; ++i) {
            if (s[i] == c) pre[c][i] = i;
            else pre[c][i] = pre[c][i-1];
        }
    }
    L[1] = nxt[p[1]][1];
    for (int i = 2; i <= m; ++i) L[i] = nxt[p[i]][L[i-1]+1];
    R[m] = pre[p[m]][n];
    for (int i = m-1; i >= 1; --i) R[i] = pre[p[i]][R[i+1]-1];
    int ans = 0, pr = 0, pl = 0;
    for (int i = m; i >= 1; --i) if (R[i]) ans = m-i+1, pr = i;
    for (int i = 1; i <= m; ++i) p[i] += 'a';
    if (ans == m) return puts(p+1), 0;
    R[m+1] = inf;
    int now = pr;
    for (int i = 1; i <= m; ++i) {
        while (R[now] <= L[i]) ++now;
        if (L[i] == n+1) break;
        if (ans < i+m-now+1) {
            ans = i+m-now+1;
            pl = i, pr = now;
        }
    }
    if (!ans) return puts("-"), 0;
    for (int i = 1; i <= pl; ++i) putchar(p[i]);
    for (int i = pr; i <= m; ++i) putchar(p[i]);
    return 0;
}