/*
*n：数组元素个数
k：目标值，需要让第一个元素达到的值
 *声明长整型变量c并初始化为0，用于计数操作次数
 *
*%d：整数格式说明符
&n, &k：变量地址，用于存储输入值
*动态分配一个大小为n的整型数组：
int* r：声明指向整型的指针r
new int[n]：在堆上分配n个整型空间
这个数组用来存储n个数值
 *r + i：指针算术，等价于&r[i]，表示数组第i个元素的地址
 *
*当数组第一个元素小于k时继续循环：
这是主循环，直到第一个元素达到目标值k为止
 *内层循环，遍历整个数组：
*如果当前元素等于k，则跳出内层循环
这意味着一旦找到等于k的元素就停止本次操作
*否则如果满足以下任一条件，则将当前元素加1：
i == n - 1：当前是最后一个元素（无需比较下一个元素）
r[i] < r[i+1]：当前元素小于下一个元素
++r[i]：将当前元素值增加1
 *操作计数器加1，记录执行了一次完整操作
 *
*释放动态分配的数组内存：
delete[]：释放数组内存的操作符
r：之前通过new分配的数组指针
 *
 *
 */
#include <cstdio>
using namespace std;

int n, k;
long c(0);

int main() {
    scanf("%d %d", &n, &k);
    int* r = new int[n];
    for (int i = 0; i < n; ++i) scanf("%d", r + i);
    while (r[0] < k) {
        for (int i = 0; i < n; ++i) {
            if (r[i] == k) break;
            else if (i == n - 1 || r[i] < r[i+1]) ++r[i];
        }
        ++c;
    }
    printf("%ld\n", c);
    delete[] r;
    return 0;
}