///时间复杂度：O(n)，空间复杂度：O(n²)（用于存储组合数）
/*
以1开头的数：第一位固定为1，其余n-1位中选k-1个1，共C(n-1, k-1)个
以0开头的数：首位为0，其余n-1位中选k个1，共C(n-1, k)个

m是要找的第几个数，k是二进制中1的个数
c[n-2][k-2] 表示在n位二进制数中，两端为1，中间n-2位中有k-2个1的方案数
如果当前n对应的方案数≥m，说明目标就在这个范围内

当前n范围内的方案数不够m个，所以跳过这些数字
m -= c[n-2][k-2] 更新m为在剩余数字中的排名
例如：如果要找第10个，但当前范围只有7个，那就跳过这7个，变成找第3个

(1ll<<(n-1))+1 创建形如 100...001 的数（n位，首尾为1）
k -= 2 因为首尾两位已经确定为1，还剩k-2个1要分配

从第n-2位到第1位（中间位）
i&&k 确保还有位数可以处理且还有1可以分配
m > c[i-1][k] 检查是否要把第i位置为1
在位置i不放置1的情况下，后面还可以放置k个1的方案数
如果目标排名m大于不放1的方案数c[i-1][k]
说明目标数字不在不放1的这些方案中
所以必须在第i位放1


m -= c[i-1][k]：跳过不包含第i位为1的那些数字
k--：使用的1的数量减1
ans += 1ll<<i：将第i位置为1
((ans+1)>>1) 将二进制形式转换为十进制表示

+1: 将末位的1加掉，可能产生进位
>>1: 丢弃最低位，得到紧凑的二进制表示

 */
#include <iostream>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

ll c[66][66];
void get(const int n=62) {
    c[0][0] = 1;//从0个元素中选0个元素的方法数为1
    for (int i = 1; i <= n; ++i) {
        c[i][0] = c[i][i] = 1;//从i个元素中选0个或i个的方法数都是1
        for (int j = 1; j < i; ++j)
            c[i][j] = c[i-1][j-1] + c[i-1][j];
    }
}


int main() {
    fast;
    get();
    ll m; int k; cin >> m >> k;
    if (k == 1 || m == 0) { cout << "1\n"; return 0; }
    int n = k;
    while (true) {
        if (c[n-2][k-2] >= m) break;
        m -= c[n-2][k-2];//如果不够，跳过这些数字
        n++;//尝试更大的n
    }
    //设置最高位和最低位为1
    ll ans = (1ll<<(n-1))+1; k -= 2;
    //最多执行 min(n-2, 原始k值) 次
    for (int i = n - 2; i&&k; --i) if (m > c[i-1][k])
        //更新剩余的排名 减少剩余需要设置的位数 将第i位置为1
        m -= c[i-1][k], k--, ans += 1ll<<i;
    cout << ((ans+1)>>1) << '\n';
    return 0;
}