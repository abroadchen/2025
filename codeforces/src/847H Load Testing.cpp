/**
a[]：原始输入数组。
q[]：前缀方向调整后，每个位置应达到的"合法值"（保证从左到右严格递增）。
r[]：前缀方向的累计代价。
e[]：后缀方向调整后，每个位置应达到的"合法值"（保证从右到左严格递增）。
f[]：后缀方向的累计代价
n：数组长度。下标从 1 开始（1 基）。
读入 a[1..n]。
q[1] = a[1]：第一个位置无需调整，前缀方向"合法值"就是它本身
对于从第 2 个到第 n 个位置，只考虑"把前面调好、让从左到右严格递增"这一方向：
q[i] = max(a[i], q[i-1] + 1)：
为了让序列从左到右严格递增（a[i] ≥ a[i-1]+1），第 i 位至少要达到 前一位要达到的值 + 1。
若 a[i] 本身就 ≥ 这个下限，则保持原值（不用加）；否则要提升到下限。
所以取两者较大者，就是要达到的"目标合法值" q[i]。
r[i] = r[i-1] + (q[i] - a[i])：
q[i] - a[i] 是把第 i 位从原值 a[i] 提到 q[i] 所需的操作次数（每次 +1）。
r[i] 累加前 i 位总共需要的操作数（前缀方向的累计代价）。
注意：这只保证了 前缀内部严格递增，即 a[1] < a[2] < ... < a[i]。
e[n] = a[n]：最后一个位置无需调整，后缀方向的合法值即本身。
从右往左遍历：
e[i] = max(a[i], e[i+1] + 1)：为了从右往左看时后面严格递增成立（等价于从左往右看，且 i 右边都固定为 e[i+1]），第 i 位至少要达到 右边一位要达标值 + 1。与前缀对称。
f[i] = f[i+1] + (e[i] - a[i])：累加后缀方向的代价，f[i] 表示从 i 到 n 全部调成"后缀合法"所需总操作数。
注意：e[] 是独立于 q[] 的另一套目标序列——它保证的是"只用调整 i 及右边就构成严格递增"。
mn 初始为两种极端情况的最小值：
f[1]：整个数组只用后缀方向调整（即 e[1..n] 方案）的代价。
r[n]：整个数组只用前缀方向调整（即 q[1..n] 方案）的代价。
取两者较小作为初始最优
枚举每个中间分界点 i：让 前缀用 q 的方案调（第 1..i 位）‍，后缀用 e 的方案调（第 i+1..n 位）‍，二者拼起来。
r[i]：调好 1..i（前缀方向）的代价。
f[i+1]：调好 i+1..n（后缀方向）的代价。
max(q[i], e[i]) - q[i]：这是衔接修正。因为前缀要求 q[i]、后缀要求 e[i+1]，而严格递增要求 q[i] < e[i+1]（至少要差 1）。若 q[i] ≥ e[i+1] 就破坏递增，需要再额外把其中一边抬高：
实际上 e[i] = max(a[i], e[i+1]+1) 已把"i 位要达到的后缀下限"记成 e[i]，包含了对 i 这一格的衔接。
这里 max(q[i], e[i]) 取两者较大作为 i 位最终要到达的值，- q[i] 是相对前缀方案多出来要补的操作数。
用 mx 记录该分界下的总代价，若小于 mn 则更新。
说明：这个"前缀 q + 后缀 e 在分界点拼接、并对衔接处补差值"的做法，本质是在所有"一个位置固定，左右分别单向调整"的方案里找最小。它是这类题常用解法的一种变式。
输出所有方案（纯前缀、纯后缀、以及各个分界拼接）中代价最小者 mn。
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;
constexpr int N = 1e6+1;
ll a[N], q[N], r[N], e[N], f[N];
int main() {
    fast;
    int n, i; cin >> n;
    for (i = 1; i <= n; ++i) cin >> a[i]; q[1] = a[1];
    for (i = 2; i <= n; ++i) {
        q[i] = max(a[i], q[i-1] + 1);
        r[i] = r[i-1] + q[i] - a[i];
    }
    e[n] = a[n];
    for (i = n-1; i >= 1; --i) {
        e[i] = max(a[i], e[i+1] + 1);
        f[i] = f[i+1] + e[i] - a[i];
    }
    ll mn = min(f[1], r[n]), mx;
    for (i = 2; i < n; ++i) {
        mx = r[i] + f[i+1] + max(q[i], e[i]) - q[i];
        if (mx < mn) mn = mx;
    }
    cout << mn;
    return 0;
}