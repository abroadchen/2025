/*
 *4行101列的二维字符数组，用于存储构造的图案
*如果n=1
第0行和第1行的第0列都设置为'a'
第2行和第3行的第0列都设置为'b'
这样形成2×2的方阵：aa在上，bb在下
 *
*如果n>1的情况：
初始化变量k=0（用于字母循环），q=0（用于行切换）
设置第0行和第1行的第0列为'a'
 *
*循环构造图案（从第0列到第n-2列）：
q ^= 1: 切换q的值（0变1，1变0），用于交替使用两组行
k = (k + 1) % 26: k递增并在26个字母间循环
q<<1 等价于 q*2，选择第0行或第2行
q<<1|1 等价于 q*2+1，选择第1行或第3行
每次填充两行，每行连续两列填入相同的字母
 *
*处理最后一列（第n-1列）：
切换q值
更新k值
在最后一列填入字母
 *
*输出构造的4×n网格：
外层循环遍历4行
内层循环遍历n列，输出每个字符
每行输出完成后换行
 *
 *
 */
#include <cstdio>
using namespace std;

int n;
char g[4][101];

int main() {
    scanf("%d",&n);
    if (n == 1) {
        g[0][0] = g[1][0] = 'a';
        g[2][0] = g[3][0] = 'b';
    } else {
        int k(0), q(0);
        g[0][0] = g[1][0] = 'a';
        for (int i = 0; i + 1 < n; ++i) {
            q ^= 1;
            k = (k + 1) % 26;
            g[q<<1][i] = g[q<<1][i+1] = 'a' + k;
            k = (k + 1) % 26;
            g[q<<1|1][i] = g[q<<1|1][i+1] = 'a' + k;
        }
        q ^= 1;
        k = (k + 1) % 26;
        g[q<<1][n-1] = g[q<<1|1][n-1] = 'a' + k;
    }
    for (int i = 0; i < 4; ++i) {
        for (int j = 0; j < n; ++j) printf("%c", g[i][j]);
        printf("\n");
    }
    return 0;
}