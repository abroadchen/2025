/**
a[30]：存放一天内所有合法"回文时刻"（换算成"一天中的第几分钟"）。开 30 够用，因为 24 小时里回文时刻很少（约二十几个）。
cnt：回文时刻的个数（a 中有效元素数）。
h, m, t：小时、分钟、当前时刻；ans：答案（等待的分钟数）
遍历小时 i 从 0 到 23，尝试构造"逆序合法的回文时刻"
x = 把小时 i 的两位数倒序后的值。例如：
i = 10：i%10==0, i/10==1 → x = 0*10 + 1 = 1；
i = 12：→ x = 2*10 + 1 = 21；
i = 21：→ x = 1*10 + 2 = 12；
i = 1（小时是一位数，实际显示 01）→ x = 1*10 + 0 = 10。
也就是"把 HH 倒过来当 MM"
分不能超过 59。若倒序后的 x > 59，说明这个反过来的"分钟"不合法，跳过（例如 23 → x=32 合法；而 19 → x=91 超过 59，跳过）
当前时刻 i:xx 的"回文分钟"是 x，把它换算成一天内的总分钟数 i*60 + x，存入 a。
这样枚举完 0-23 小时，a[1..cnt] 就包括了全天所有合法回文时刻，且由于 i 递增，a 是升序排列的
读入 HH:MM，换算成当前时刻的总分钟数 t
a[cnt] 是全天最后一个回文时刻。若当前时间 t 已经过了它，说明今天之内不会再出现回文，需要跨到明天：
1440 - t：今天还剩多少分钟到午夜 24:00；
+ a[1]：再加上明天凌晨的第一个回文时刻（a[1] 记为第几分钟）。
两者相加即"从现在到下一个回文还要等多少分钟"
否则（当前时间 ≤ 最后一个回文），在升序数组 a[1..cnt] 里用 lower_bound 找第一个 ≥ t 的元素下标，取出的时刻减去 t，就是等待的分钟数。
注意：如果 t 本身就是回文（t 正好等于 a 中某元素），则找到的是它自己，ans = 0——这点与题意一致（已处于回文则无需等待）
输出最少等待分钟数
 */
#include <bits/stdc++.h>
using namespace std;

int a[30], cnt, h, m, t, ans;
int main() {
    for (int i = 0; i <= 23; ++i) {
        int x = (i%10)*10+i/10;
        if (x > 59) continue;
        a[++cnt] = i*60 + x;
    }
    scanf("%d:%d", &h, &m); t = h*60 + m;
    if (t > a[cnt]) ans = 1440 - t + a[1];
    else ans = a[lower_bound(a+1, a+cnt+1, t)-a] - t;
    printf("%d", ans);
    return 0;
}