int b[1005] = {
    0,0,1,2,1,2,0,1,2,0,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,
    0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,
    0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,
    0,2,1,2,0,2,1,2,0,2,1,2,0,2,1,2,0,2,1
};

int p;
int get(int l, int r) {
    l = p + 1 - l, r = p + 1 - r;
    return ((l + r) * (l - r + 1) / 2) % mod;
}

signed main() {
    fast;
    int n, bs2 = 0, bs = 0, dp[1005][1005];
    constexpr int cnt = 500;
    cin >> n >> p; p -= 1;
    for (int i = 1; i <= cnt; ++i) {
        if (b[i] == 0) { if (a[i] > p) break; continue; }
        if (b[i] == 2) {
            if (a[i] > p) break;
            bs2 += get(a[i], min(a[i+1] - 1, p));
            bs2 %= mod;
            continue;
        }
        if (a[i] > p) break;
        bs += get(a[i], min(a[i+1] - 1, p)); bs %= mod;
    }
    const int all = get(1, p); dp[0][0] = 1;
    for (int i = 0; i <= n; ++i) for (int j = 0; j <= 3; ++j) {
        dp[i+1][j] += dp[i][j] * (all - bs - bs2); dp[i+1][j] %= mod;
        dp[i+1][j] += dp[i][j^1] * bs; dp[i+1][j] %= mod;
        dp[i+1][j] += dp[i][j^2] * bs2; dp[i+1][j] %= mod;
    }
    int ans = 0;
    for (int i = 1; i <= 3; ++i) ans += dp[n][i];
    cout << (ans % mod + mod) % mod << '\n';
    return 0;
}