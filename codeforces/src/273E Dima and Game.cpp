/*
*首先根据公式重新映射 l 和 r 到新的位置（类似镜像翻转操作）。
计算从 l 到 r 所有连续整数之和，即等差数列求和公式 (首项 + 尾项) × 项数 ÷ 2
*n: 输入的一个参数（题目中的某个限制条件）
bs2, bs: 分别记录不同类别的前缀和
dp[1005][1005]: 动态规划表，最大支持到 1004×1004
cnt: 编译期确定的常量，表示循环上限
 *
*对于每个索引 i 从 1 到 cnt：
如果 b[i] == 0，跳过当前迭代；
如果 b[i] == 2，累加区间 [a[i], min(a[i+1]-1, p)] 内的所有数字之和到 bs2；
否则（也就是 b[i] == 1），同样累加到 bs；
每次都判断是否超出范围 p 来决定是否提前终止循环
 *
*all 存储的是从 1 到 p 所有正整数的总和；
设置动态规划初始状态：dp[0][0] = 1 表示起点状态合法且唯一
 *
*j^1 实现了状态 0↔1, 2↔3 的切换
j^2 实现了状态 0↔2, 1↔3 的切换
 *
*第0类：b[i] == 0（既不在 bs 也不在 bs2 中计算）
第1类：b[i] == 1（在 bs 中计算）
第2类：b[i] == 2（在 bs2 中计算）
 */
#include <iostream>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define int long long
#define mod 1000000007
using namespace std;

