/**
c[] 是计数数组，值域扩到 1e6+1。
inf = 2e9，而 -inf（取负）表示"淘汰"标记
每读到一个数 x：

++c[x]：先让 x 的计数加 1（这次读到含在内）。
判断该新计数值是否 <= c[m]（m 当前的计数），并且 x != m：
若同时满足，说明 x 的计数到目前为止没有超过 m，就把 c[x] 覆盖为 -inf。
否则（x 的计数已经超过/持平领先 于 m，或是 m 自身），保留真实计数。
x != m 这个条件保证：基准数 m 自己的计数永远不被清成 -inf，它会一直正常累计。
剪枝的意图：m 在处理过程中计数只增不减。一旦在某个时刻数字 x 的计数被 m 甩在后面（<= c[m]），就认为 x 大概率最终赢不了，于是直接淘汰，省去后续维护。但要注意——这个剪枝并不是在所有输入上都严格正确（见文末"注意事项"）
从小到大遍历所有数字 i。
找到第一个 i != m 且 c[i] >= c[m] 的，输出它并结束。
若全程都没有，输出 -1（表示不存在任何非 m 的数字，其出现次数能不少于 m）。
因为 -inf 很大为负，被淘汰的数字绝不满足 c[i] >= c[m]，所以不会被打出来。
只有出题保证 m 在序列中的"出现进度"始终能压住其他数（比如 m 本身是读入末尾才集中出现的强众数，且任意其他数一旦被 m 追平就无望反超）时，这句剪枝才正确
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 1e6+1, inf = 2e9;
int n, m, c[N];
int main() {
    fast;
    cin >> n >> m;
    while (n--) {
        int x; cin >> x;
        if (++c[x] <= c[m] && x != m) c[x] = -inf;
    }
    for (int i = 1; i < N; ++i)
        if (i != m && c[i] >= c[m]) {
            cout << i << '\n';
            return 0;
        }
    cout << "-1\n";
    return 0;
}