/**
真正学会的起点..
N = 27：因为用 at[] 以 1-26 表示字母 a-z（多开一位做下标 1 起点），所以数组开到 27。
n, k：全局变量。n 表示接下来要读几个字母，k 表示要选的字母个数。
at[N]：布尔标记数组，at[1..26] 分别标记字母 a-z 是否出现
定义 c 存临时读入的字符，s 用来构造最终的字母串。
memset(at, 0, sizeof(at))：每次新数据前把 at[] 全部清零。
循环读入 n 个字符 c，并把 at[c-'a'+1] 置为 1。
c - 'a' 把字符 a-z 转成 0-25。
+1 变成 1-26，正好对应 at[1]-at[26]。
这一步是在标记哪些字母出现过（去重，重复出现只记一次）
遍历 i = 1..26（N-1 = 26）。
如果 at[i] 为真（即该字母出现过），就把它加入 s：
'a' + i - 1：把下标 i 还原成字母（i=1 → 'a'，i=2 → 'b'...）。
⚠️ 代码 bug 点：循环体里写了 i++。当 at[i] 为真时，进入 if 后 i 会自增一次，而 for 循环的 i++ 又会再自增一次，所以实际会跳过下一个字母的下标检查。
也就是说：如果 at[1](a) 为真，处理后 i 变成 2，再执行 for 的 i++ 变 3，跳过了下标 2；下一轮从 i=3 开始。
这可能造成某些 at[] 标记对应的字母被漏掉。
不过，因为靠 at[1..26] 依次扫描并 s +=，前面已经有 memset + 逐个标记的方式把所有出现的字母去重记录在 at[] 里，所以即便这里漏检个别下标，s 仍会包含前 k 个（按升序）被访问到的字母——但若某个标记可怜的 at[i] 因自增跳过了，它就不会进 s。
结论：这里 i++ 是多余/错误的写法，会导致漏掉部分字母；但代码原作者可能以为它能避免重复？其实是遗漏 bug。我们以"按事实解释"为主：它会导致在 at[i] 为真那一个下标后，跳过紧邻的下一个下标
如果 s 里收集到的字母个数 < k，说明不够选，输出 -1。
否则：
取 s 的前 k 个字符，把每个字符转成数字 s[i] - 'a' + 1（a=1, b=2, ..., z=26）。
累加它们的和到 res，输出 res
*/
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)

using namespace std;

constexpr int N = 27;

int n, k;
bool at[N];
int main() {
    fast;
    while (cin >> n >> k) {
        char c; string s;
        memset(at, 0, sizeof(at));
        for (int i = 0; i < n; i++) {
            cin >> c;
            at[c-'a'+1] = 1;
        }
        for (int i = 1; i <= N-1; i++) if (at[i]) s += 'a' + i++ - 1;//"相邻字母不能同选"的约束
        if (s.length() < k) cout << -1 << '\n';
        else {
            int res = 0;
            for (int i = 0; i < k; i++) res += s[i] - 'a' + 1;
            cout << res << '\n';
        }
    }
    return 0;
}