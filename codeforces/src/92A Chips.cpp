/*
*n * (n + 1) / 2 计算的是1到n的连续整数和（等差数列求和公式）
这个操作将m限制在一个周期内，因为序列具有周期性
*这是在求解不等式 x(x+1)/2 ≤ m 的最大整数解
也就是找到最大的x，使得1+2+3+...+x ≤ m
通过求解二次方程 x² + x - 2m = 0 得到 x = (√(8m+1) - 1)/2
 *
*周期长度：前n组的总长度是 1+2+3+...+n = n(n+1)/2
取模操作：m %= n*(n+1)/2 将问题简化到一个周期内
组定位：通过求解 x(x+1)/2 ≤ m 找到m所在的组
位置计算：m - x*(x+1)/2 给出在该组内的偏移量
O(n)的遍历问题转化为O(1)的数学计算
 */
#include <cmath>
#include <cstdio>
using namespace std;

int main() {
    int n, m; scanf("%d %d",&n,&m);
    m %= n * (n + 1) / 2;
    int x = (sqrt(8 * m + 1) - 1) / 2.;
    printf("%d\n", m - x * (x + 1) / 2);
    return 0;
}