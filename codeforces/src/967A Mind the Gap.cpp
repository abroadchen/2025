/**
n：事件数量；s：需要连续空闲的分钟数。
lh, lt：上一个（最近一个）事件的小时、分钟。
lst：上一个事件的绝对分钟数（now 的累计），初值设为 -s-1，目的是把时间线"提前"，让第一个事件从 0 开始就能被正确判断（相当于前面有一个无限早的"虚拟事件"）。
nh, nt：当前遍历读到的事件的小时、分钟（也可当输出用）。
now：当前事件换算成的绝对分钟
lst = -s-1、lt = -s-1：把"上一个事件时刻"人为设在很早就结束，这样第 1 个事件前面也能进行空闲检查。
这些初值的选择保证了"从 0 点 0 分之前开始就有一段足够长的空闲"被视为可用的逻辑。
可确证：lst/lt 初始为 -s-1，把时间线前置到负的时刻，以便第一个事件前也能做间隔判断
关键条件 now - lst >= 2*s+2：

now - lst 是当前事件与上一个事件之间的间隔分钟数。
阈值是 2*s + 2，而不是 s。这里隐含一个约束：空闲窗口两端可能都要各留至少 1 分钟的缓冲（比如"前后各留 1 分钟"），所以真正可安排的空闲 = 间隔 - 2，要 ≥ s，即 间隔 ≥ s+2……再细化成 2s+2 则说明间隔里要能容纳两个这样的窗口或者窗口前后各留 s/2 之类的设定
它取的是上一个事件结束再加 s+1 分钟的时刻：
lt + s + 1 是"上一个事件分钟 + s + 1"。
除以 60 得进位的小时，加到 lh 上；取模 60 得分钟。
也就是说，把输出点安排在"上一个事件结束后再空出 s+1 分钟"的位置（即保证后面还有至少一段可用的连续空闲）。
输出后 return 0，只输出这第一个符合条件的点
若间隔不足，则把当前事件记为"上一个事件"，继续下一轮检查
如果全部 n 个事件都没触发足够间隔的条件（即每两个相邻事件间隔都 < 2s+2），则不再判断，直接输出"最后一个事件时刻 + s+1 分钟"作为答案。
同样是对应时刻取 (lt+s+1) 的小时/分钟
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)

using namespace std;

int n, s;
int main() {
    fast;
    cin >> n >> s;
    int lh = 0, lt = -s-1, lst = -s-1, nh = 0, nt = 0, now = 0;
    for (int i = 1; i <= n; i++) {
        cin >> nh >> nt; now = nh*60+nt;
        if (now - lst >= 2*s+2) {
            nh = lh + (lt+s+1)/60;
            nt = (lt+s+1)%60;
            cout << nh << ' ' << nt << '\n';
            return 0;
        }
        lst = now; lh = nh; lt = nt;
    }
    nh = lh + (lt+s+1)/60;
    nt = (lt+s+1)%60;
    cout << nh << ' ' << nt << '\n';
    return 0;
}