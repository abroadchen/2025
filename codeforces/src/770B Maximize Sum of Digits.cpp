/**
m[N]：读入的原数（字符串形式）。
s[N]：将原数拆成一位一位的数字数组（低位在前）。
k：数字位数。
s1：原数的各位数字之和。
s2：临时变量（后缀数字之和

读入字符串数字 m。
把数字从低位到高位存入 s[]（即 s[0] 是个位，s[1] 是十位……），并同时累加 s1 = 所有位数字之和。
例：若 m="12345"，则 s[0]=5,s[1]=4,s[2]=3,s[3]=2,s[4]=1，s1=1+2+3+4+5=15
从最高位（i=k-1）往低遍历，i>0。
s2 += s[i]：把当前位及所有更高位累加进 s2（suffix之和）。
if (s[i-1] == 9) continue：若下一位（更低一位）是 9，跳过本层——因为 9 已经最大，无法在它这一位做"进一减一"调整。
if (s2-1+9*i > s1)：这是贪心判断的关键。含义是：
假设我们把第 i-1 位（当前考察的最低位）减 1，那么为了让总和不变，需要把某一位补回。这里 s2-1 是"减完后的后缀和"，+9*i 是"把低位 i 位全填成 9 能增加的和"，两者相加大于原和 s1，说明可以通过把更低位全部改成 9 来弥补这个减 1，从而得到更大的数。
若成立：更新 s1 = s2-1+9*i；s[i]--（把第 i 位减 1）；然后把第 i-1 位及所有更低位置为 9（for j=i-1..0: s[j]=9）；break 结束。
这步的实质：为了让构造出的数尽可能大，找到一个位置把它减 1、并把后面所有低位改为 9，同时保持数字和与原数相同
输出：先输出最高位 s[k-1]（若最高位为 0 则不输出，避免前导 0），然后从次高位到个位依次输出 s[k-2]...s[0]。
即从高位到低位把数字数组打印出来，得到最终构造的数
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;

constexpr int N = 30;
char m[N];
int s[N], k, s1, s2;
int main() {
    fast;
    cin >> m;
    int len = strlen(m);
    for (int i = len-1; i >= 0; --i) {
        s[k++] = m[i] - '0';
        s1 += s[k-1];
    }
    for (int i = k-1; i > 0; --i) {
        s2 += s[i];
        if (s[i-1] == 9) continue;
        if (s2-1+9*i > s1) {
            s1 = s2-1+9*i; s[i]--;
            for (int j = i-1; j >= 0; --j) s[j] = 9;
            break;
        }
    }
    if (s[k-1]) cout << s[k-1];
    for (int i = k-2; i >= 0; --i) cout << s[i];
    cout << '\n';
    return 0;
}