/**
真正学会的起点..
处理 '0'（竖条，占本列 2 行）

'0' 方块放在同一列、上下两格。
用 c 的奇偶切换两套位置，交替放置互不重叠：
当 c == 0（偶数次 0）：放 "1 1"（第 1 行、第 1 列，占 (1,1) 和 (2,1)）。
当 c == 1（奇数次 0）：放 "3 1"（第 3 行、第 1 列，占 (3,1) 和 (4,1)）。
每次 c++ 后 %2，实现 0/1 交替。这样两个竖条一个占上方两格、一个占下方两格，永远不重叠。
处理 '1'（横条，占两列）

'1' 方块横向占两块，放在第 4 行。
用 r 的奇偶切换：
r == 0（偶数次 1）→ 放 "4 3"（第 4 行、第 3 列起，占 (4,3) 和 (4,4)）。
r == 1（奇数次 1）→ 放 "4 1"（第 4 行、第 1 列起，占 (4,1) 和 (4,2)）。
同样靠 r 0/1 交替，两个横条分占第 4 行左右两半，互不重叠。
每次输出后换行。
*/
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)

using namespace std;

string s;
int main() {
    fast;
    cin >> s;
    int r = 0, c = 0;
    for (char d : s) {
        if (d == '0' && !c) { cout << "1 1"; c++; c %= 2; }
        else if (d == '0') { cout << "3 1"; c++; c %= 2; }
        else if (d == '1' && !r) { cout << "4 3"; r++; r %= 2; }
        else { cout << "4 1"; r++; r %= 2; }
        cout << '\n';
    }
    return 0;
}