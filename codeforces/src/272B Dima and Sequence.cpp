/*
*第一轮并行计算：
0x55555555 = 01010101010101010101010101010101（二进制）
n & 0x55555555：提取n的奇数位
n >> 1：n右移1位
(n >> 1) & 0x55555555：提取n右移后的奇数位
将两部分相加，得到每2位中1的个数
*第二轮并行计算：
0x33333333 = 00110011001100110011001100110011（二进制）
计算每4位中1的个数
*第三轮并行计算：
0x0f0f0f0f = 00001111000011110000111100001111（二进制）
计算每8位中1的个数
*第四轮并行计算：
0x00ff00ff = 00000000111111110000000011111111（二进制）
计算每16位中1的个数
*第五轮计算：
0x0000ffff = 00000000000000001111111111111111（二进制）
计算整个32位中1的个数
 *
*n：元素个数
a：临时变量，用于读取每个元素
c[32] = {}：整型数组，大小为32，初始化为全0，用于统计每个位数的元素个数
*bit(a)：计算a中1的个数
c[bit(a)]++：将对应计数器加1
 *
 *1ll * i * 1ll * (i - 1) / 2：计算组合数C(i,2) = i*(i-1)/2
 *时间复杂度：O(n)，其中n是元素个数。 空间复杂度：O(1)，只需要固定大小的计数数组
 */
#include <iostream>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

int bit(int n) {//n的二进制表示中1的个数 汉明重量/Hamming Weight
    n = (n & 0x55555555) + ((n >> 1) & 0x55555555);
    n = (n & 0x33333333) + ((n >> 2) & 0x33333333);
    n = (n & 0x0f0f0f0f) + ((n >> 4) & 0x0f0f0f0f);
    n = (n & 0x00ff00ff) + ((n >> 8) & 0x00ff00ff);
    n = (n & 0x0000ffff) + ((n >> 16) & 0x0000ffff);
    return n;
}

int main() {
    fast;
    int n, a, c[32] = {}; cin >> n;
    while (n--) {
        cin >> a;
        c[bit(a)]++;
    }
    ll ans = 0;
    for (const int i : c) ans += 1ll * i * 1ll * (i - 1) / 2;
    cout << ans << '\n';
    return 0;
}