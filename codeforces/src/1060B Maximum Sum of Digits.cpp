/**
真正学会的起点..
循环取末位累加，再整除 10，直到 x 为 0。
返回 x 的各位数字之和
读入 n。
若 n < 9：没法拆出 9，此时为了让数字和最大，最好的拆分是 a=n, b=0（不拆），数字和 = n（一位数各位和=自身），直接输出 n。a=0 数字和 0
贪心构造 x：让 x 成为"≤ n 的最大的全 9 数"（形如 9、99、999…）。循环条件 x*10+9 <= n：只要再加一位 9 仍不超 n，就把 x 接一位 9（x = x*10+9）。
例如 n=99，x 依次 =9、→99（9*10+9=99≤99 成立）→ 再试 999>99 停，x=99。
例如 n=100，x=9→99(≤100)→999>100 停，x=99。
输出 f(x) + f(n-x)：两部分的各位和之和即为最大答案。
为什么这样最优：数字和的损失来自"进位"（比如 1+9=10 会把各位和从 10 压成 1+0=1）。要让数字和最大，应避免在 a+b=n 时发生进位，即尽量把每个数位上的和维持在 9（无进位）。让 a 取"全 9"（每加一位 9 都不进位到达下一位），另一半 n-a 恰好落到个位附近，能把进位压制到最少。这是该题的官方贪心归纳。
*/
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

ll f(ll x) {
    ll sum = 0;
    while (x) {
        sum += x % 10;
        x /= 10;
    }
    return sum;
}

int main() {
    fast;
    ll n; cin >> n;
    if (n < 9) { cout << n; return 0; }
    ll x = 0;
    while (x*10+9 <= n) x = x*10+9;
    cout << f(x) + f(n-x);
    return 0;
}