/*
*创建大小为5的向量，初始化为0
读入n个物品的大小，统计每种大小的物品数量
 *
 *
*每个大小为4的物品必须独占一个箱子
直接计入所需箱子数
 *
*每个大小为3的物品独占一个箱子
每个这样的箱子还可以放入1个大小为1的物品
因此从可用的大小为1的物品中减去v[3]个
 *
*两个大小为2的物品可以放在同一个箱子中
如果有偶数个：v[2]/2个箱子
如果有奇数个：v[2]/2 + 1个箱子
奇数个时，剩余的那个大小为2的物品可以搭配2个大小为1的物品
 *
*v[2] / 2: 整除部分，表示可以完全装满的箱子数
v[2] % 2: 余数部分，表示无法完全装满的物品数（需要额外箱子）
 *
 *
*将剩余的大小为1的物品每4个放在一个箱子中
如果不能整除，还需要一个额外箱子
 *
 *
*时间复杂度：O(n)
空间复杂度：O(1)
 *
 */
#include <iostream>
#include <vector>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;


int main() {
    fast;
    int n; cin >> n;
    vector<int> v(5, 0);
    int t;
    do {
        cin >> t;
        ++v[t];
    } while (--n);

    int ans = v[4];
    ans += v[3]; v[1] -= v[3];
    ans += v[2] / 2 + v[2] % 2; v[1] -= 2 * (v[2] % 2);
    if (v[1] > 0) ans += v[1] / 4 + (v[1] % 4 > 0);
    cout << ans << '\n';
    return 0;
}