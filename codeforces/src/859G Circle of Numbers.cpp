/**
读入长度 n 的二进制字符串 s，把每个字符 '0'/'1' 转成数值存进 f[i]（只可能是 0 或 1）
外层：把 v 从 n 开始分解质因数（?p 递增、v 被除到不含 p 的因子）。

对 n 的每一个不同的质因子 p，执行一次变换：

step = n / p（即 n/p，下称 d）；
g[i] = f[(i - d + n) % n] - f[i]：对循环序列做步长为 d 的差分——即把"前移 d 位"的对应元素减去当前元素。+n 取模是为了处理循环下标的负数。
结果写回 f。
例如 n=6，质因子为 2 和 3：

第一次 p=2，d=3，做 f[i] ← f[i-3] - f[i]（循环）；
第二次 p=3，d=2，做 f[i] ← f[i-2] - f[i]（循环）
对所有 f[i] 做按位或：只要任何一项非 0 → ans != 0 → 输出 NO；
全部为 0 → 输出 YES。
因为初始 f 只有 0/1，多次加减后仍为整数；判定"经过这些差分变换后，整个序列是否全为 0"

对步长 d = n/p 做 f[i] ← f[(i-d) mod n] - f[i]，等价于在循环群 Z_n 上乘以 (x^d - 1) 对应的多项式算子（在模 2 意义下是类型特征多项式 / 循环码的校验）。

若某个质因子对应的差分（x^{n/p} - 1）整除序列对应的多项式，则该质因子变换会让序列退化；
当所有质因子对应的算子作用后序列完全归零，说明原序列属于"每个不同质因子步长差分都为零"的特殊子空间——这正是判定某种周期性/特殊结构（例如序列是否完全由某种高阶差分规律约束）的条件。
通俗理解：这是一个在有限循环序列上做的离散差分滤波，逐质因子地"抹平"高频结构，最后看是否能被整个抹成全零。属于循环差分析 / 周期序列刻画类问题，常见于组合/代数题目（如"序列能否由特定周期规律生成/一步归零"）
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 1e5+5;

string s;
int f[N], g[N], ans;
int main() {
    fast;
    int n; cin >> n >> s;
    for (int i = 0; i < n; ++i) f[i] = s[i] - 48;
    for (int v = n, p = 2; p <= v; ++p) {
        if (v%p == 0) {
            while (v%p == 0) v /= p;
            for (int i = 0; i < n; ++i) g[i] = f[(i-n/p+n)%n] - f[i];
            for (int i = 0; i < n; ++i) f[i] = g[i];
        }
    }
    for (int i = 0; i < n; ++i) ans |= f[i];
    cout << (ans == 0 ? "YES" : "NO") << '\n';
    return 0;
}