#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;
constexpr int N = 5e5+5;

struct node { int x, y, z; } p1[13], p2[13];

ll f[N][2][2][3], g[2][2][3];
int t1, t2;
vector<int> e[N];
void dfs(int u, int fa) {
    f[u][0][0][0] = 1, f[u][0][0][2] = 1, f[u][1][0][1] = 1;
    for (int v : e[u]) {
        if (v == fa) continue;
        dfs(v, u);//先自底向上算完子树 v
        memcpy(g, f[u], sizeof f[u]);//把 u 当前的累计 DP 表复制到 g
        memset(f[u], 0, sizeof f[u]);//清空 f[u]，准备重新合并
        t1 = 0, t2 = 0;
        for (int c1 = 0; c1 <= 1; ++c1)
            for (int c2 = 0; c2 <= 1; ++c2)
                for (int c3 = 0; c3 <= 2; ++c3) {
                    if (g[c1][c2][c3]) p1[++t1] = {.x = c1, .y = c2, .z = c3};//父侧非零状态
                    if (f[v][c1][c2][c3]) p2[++t2] = {.x = c1, .y = c2, .z = c3};//子树侧非零状态
                }
        for (int i = 1; i <= t1; ++i) {
            int c1 = p1[i].x, c2 = p1[i].y, c3 = p1[i].z;
            for (int j = 1; j <= t2; ++j) {
                int c4 = p2[j].x, c5 = p2[j].y, c6 = p2[j].z;
                ll w = g[c1][c2][c3]*f[v][c4][c5][c6];
                if (!c2) {
                    if (!c5) {
                        if (!c1&&c4&&!(c3&&c6)) f[u][c1][c2][max(c3,c6)] += w;//①
                        if (!c1&&!c4&&!(c3&&c6)) f[u][1][c2][max(c3,c6)] += w;//②
                        if (c1&&c4&&!(c3&&c6)) f[u][c1][c2][max(c3,c6)] += w;//③
                        if (c6&&c3==c6) f[u][c1][1][0] += w;//④
                        if (c6&&!c3) f[u][c1][1][c6] += w;//⑤
                    } else {
                        if (!c3) {
                            if (!c1&&c4) f[u][c1][1][c6] += w;//B1
                            if (!c1&&!c4) f[u][1][1][c6] += w;//B2
                            if (c1&&c4) f[u][c1][1][c6] += w;//B3
                        } else {
                            if (c6==c3) {
                                if (!c1&&c4) f[u][c1][1][0] += w;//B4
                                if (!c1&&!c4) f[u][1][1][0] += w;//B5
                                if (c1&&c4) f[u][c1][1][0] += w;//B6
                            }
                        }
                    }
                } else {
                    if (!c5) {
                        if (c3==c6) {
                            if (!c1&&c4) f[u][c1][1][0] += w;//C1
                            if (!c1&&!c4) f[u][1][1][0] += w;//C2
                            if (c1&&c4) f[u][c1][1][0] += w;//C3
                        } else {
                            if (!c6) {
                                if (!c1&&c4) f[u][c1][1][c3] += w;//C4
                                if (!c1&&!c4) f[u][1][1][c3] += w;//C5
                                if (c1&&c4) f[u][c1][1][c3] += w;//C6
                            }
                        }
                    }
                }
            }
        }
    }
}

int main() {
    fast;
    int n; cin >> n;
    if (n&1) { cout << 0; return 0; }
    for (int i = 1, x, y; i < n; ++i)
        cin >> x >> y, e[x].push_back(y), e[y].push_back(x);
    dfs(1, 0);
    cout << f[1][1][1][0] << '\n';
    return 0;
}