/**
真正学会的起点..
cnt[i]：数值 i 出现的次数；
c1：出现恰好 1 次的不同数值个数；
c3：出现至少 3 次的不同数值个数；
f1：交替标记（给出现 1 次的元素轮流分 A/B）；
f2：是否已经用掉那个"≥3 的元素"来校准。
目标是让 A、B 两组各含相同的大集合（每个出现过的值两边都要有）。
出现次数为 1 的值，没法拆，只能整给 A 或整给 B。要让最终"集合元素相同"，就需要把这些"单次项"合理分配。
直观上：出现 1 次的占了 c1 个"必须两边各有一个槽位"的位置——本质是需要偶数个单次项来做配对。若 c1 为奇数，则必须靠一个 ≥3 的元素两边都各放一个、但把多余的那个单独丢给一边来补平奇偶 → 需要 c3 ≥ 1。
因此：c1 为奇数 且 没有 ≥3 的元素时 → 无解 NO。
反之：

若 c1 为偶数 → 单次项可以均匀交替分配，直接可行；
若 c1 为奇数但有 c3 ≥ 1 → 用那个 ≥3 的元素调节，也可行
情况 1：cnt[a[i]] == 1（出现 1 次的值）

用 f1 交替输出 A、B。
效果：把 c1 个单次项轮流分给 A、B 两边。由于此时已通过判定保证 c1 是偶数（或已用别的方式补齐），所以两组各得一半单次值 → 两边都能占到自己需要的槽位。
情况 2：cnt[a[i]] >= 3 && c1%2 && !f2

当 c1 是奇数且尚未用过调节元素时：把该元素输出 B（并置 f2=1 标记已用）。
这个 ≥3 的元素本该在两边各有一个（作为公共集合成员），但第 3 个及以上是"多余"的；把"其中一个"单独给 B（或先给 B），配合单次项形成正确配比。
之后的其它该值元素会走 else 输出 A，从而达成两边都有它。
作用：用 ≥3 元素的多余副本去填补单次项奇偶造成的缺口。
情况 3：其它（else）

其余元素统一输出 A（包括次数 ≥2 且非调节对象的重复部分）
*/
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define rep(i,n) for (int i=1; i<=n; i++)
using namespace std;

constexpr int N = 105;

int n, a[N], cnt[N], c1, c3;
bool f1, f2;
int main() {
    fast;
    cin >> n;
    rep(i,n) { cin >> a[i]; cnt[a[i]]++; }
    rep(i,N) {
        if (cnt[i] == 1) c1++;
        if (cnt[i] >= 3) c3++;
    }
    if (c1%2 && !c3) cout << "NO";
    else {
        cout << "YES\n";
        rep(i,n) {
            if (cnt[a[i]] == 1) {
                if (!f1) cout << 'A'; else cout << 'B';
                f1 = !f1;
            } else if (cnt[a[i]] >= 3 && c1%2 && !f2) {
                cout << 'B'; f2 = 1;
            } else cout << 'A';
        }
    }
    return 0;
}