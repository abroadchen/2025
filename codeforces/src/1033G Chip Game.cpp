/**
真正学会的起点..
n：给定数的个数；m：值域上界（数值都在 [0,m]）。
b[]：装 a[j] % i 的余数，int 即可。
a[]：原始给定数，可能较大所以用 ll。
a1, a2：两类计数的累加器（答案会很大，用 ll）
读入 n 个数，存到 a[1..n]
枚举每个模数 i，从 2 到 2m。(m<<1 即 2*m。)
去 2m 是因为后面的"反射区间"会用到 i-l / i-r（可接近 i-1），必须把 i 枚举到超过 m 的范围才能覆盖所有 [0,m] 内可能出现的余数关系
把每个数对当前模数 i 取余，得到 n 个余数存入 b[1..n]
将这 n 个余数升序排序。
b[n+1] = i-1：在末尾塞一个哨兵，它等于余数的最大可能值 i-1。这样最后一段区间能延伸到 i-1（再和 m 取小
预处理两个阈值：

b[n] 是最大的余数，l2 = b[n]/2 是它的"一半"。
b[n-1] 是次大的余数，l1 = b[n-1]/2 是它的一半。
这两个值在后面被当作"下限"，用来筛选余数要落在某个半区之上
l：从 b[j]+1 开始，即上一个余数之后紧邻的整数。
r：到 b[j+1]（下一个余数/哨兵）为止，但用 m 封顶。
这样 [l, r] 就是排序后两个相邻余数之间的空隙（即原来余数都不落在这里），j=0 时 [1, b[1]] 之前那段。若 l>r 说明空隙为空，跳过
j 是当前前面的余数个数，n-j 表示比 b[j] 更大的余数个数。根据 (n-j) 的奇偶性决定用 l1 还是 l2 作下限、累加到 a1 还是 a2
奇数的分支（累加进 a1）：

l = max(l, l1+1)：把左端再往上抬，要求余数 > l1（即超过"次大余数的一半"）。
核心这段就是求反射区间的交：
区间 [l, r] 对 i/2 的镜像是 [i-r, i-l]。
L = max(l, i-r)、R = min(r, i-l) 是 [l,r] 与自己镜像的重叠部分，即同时满足"x 落在空隙里"且"i−x 也落在空隙（对应半区）里"的整数个数。
max(0, R-L+1) 就是这个交集的长度（可能为空），累加进 a1
偶数分支（累加进 a2）：逻辑与上面完全相同，只是下限用 l2（> 最大余数的一半），计数累加到 a2。

一句话：对每个模数 i，在排序余数之间的每个"空隙"里，统计满足"自身余数、及其关于 i/2 的镜像"都落在规定半区之上的整数个数，按 n−j 的奇偶分别归入 a1 / a2
全部 [0,m] 上的序偶共有 m*m 个。a1 + a2 是已统计出的两类，剩下的数用 2r 表示（利用了某种对称性让两部分各占 r），于是 r = (m² − a1 − a2)/2。
最终输出 r  r  a1  a2 四个数——因为过分对称，把最小的两个量合并成两个相等的 r，所以打印成"r r a1 a2"
*/
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

constexpr int N = 105;

int n, m, b[N];
ll a[N], a1, a2;
int main() {
    fast;
    cin >> n >> m;
    for (int i = 1; i <= n; i++) cin >> a[i];
    for (int i = 2; i <= m<<1; i++) {
        for (int j = 1; j <= n; j++) b[j] = a[j]%i;
        sort(b+1, b+n+1); b[n+1] = i - 1;
        int l1 = b[n-1]/2, l2 = b[n]/2;
        for (int j = 0; j <= n; j++) {
            int l = b[j] + 1, r = min(b[j+1], m);
            if (l > r) continue;
            if ((n-j)&1) {
                l = max(l, l1+1);
                int L = max(l, i-r), R = min(r, i-l);
                a1 += max(0, R-L+1);
            } else {
                l = max(l, l2+1);
                int L = max(l, i-r), R = min(r, i-l);
                a2 += max(0, R-L+1);
            }
        }
    }
    ll r = ((ll)m*m-a1-a2)/2;
    cout << r << ' ' << r << ' ' << a1 << ' ' << a2 << '\n';
    return 0;
}