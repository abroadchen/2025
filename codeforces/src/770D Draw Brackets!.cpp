/**
s[N]：读入的括号串。
res[N][M]：二维字符画布，最终存放图形
读入长度 n 和括号串 s。
d：当前"深度"（所在行号）。w：当前列号（画布横向游标）。h：记录最大深度（图形高度）

遇到 [（左括号，上升段）‍：
res[d][w]='+'：当前点画 +（折点）。
res[d][w+1]='-'：向右一格画 -（水平延伸）。
d++：深度加 1（进入下一行，向"上方"走——实际上 d 增大表示上行）。w++：列右移。
遇到 ]（右括号，下降段）‍：
d--：深度减 1（向"下方"走）。
if (s[i-1]=='[') w += 3：若前一个是 [（即恰好构成一个完整小山峰 []），列号额外多跳 3——这是为了给相邻的独立小峰之间留出空隙。
res[d][w]='+'：画 +。
res[d][w-1]='-'：向左一格画 -。
w++：列右移。
每步更新 h = max(h, d)，记录到达的最大深度（图形高度）。
这段实质：把括号串解释成"上上下下"的折线，[ 往深里走、] 往浅里走，并用 +、- 画出轮廓的最低层（到 d 从某个值打到某个值）。

镜像对称复制：把第 0..h 行逐行镜像到 h+1..2h 行（以深度 h 为对称轴），使图形上下对称。效果是：如果上方画了上边界，下方就自动得到下边界，整体成一个封闭对称的波形
逐列填充竖线：对每一列 j，从上到下扫描：
当遇到 +（折点，即当前列的边界）时，翻转 k（奇偶标记，k 在 0/1 间切换）。
若当前位置为空字符 \0（!res[i][j] 为真），则填上 " |"[k]：k=0 时填空格，k=1 时填 |。
效果：在边界与边界之间的"内部"填上竖线 |，形成填充的图形
从第 0 行到第 2h 行逐行输出整个图形
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 105, M = 255;
char s[N], res[N][M];
void solve() {
    int n, d = 0, w = 0, h = 0;
    cin >> n >> s;
    for (int i = 0; i < n; ++i) {
        if (s[i] == '[') {
            res[d][w] = '+';
            res[d][w+1] = '-';
            d++, w++;
        } else {
            d--;
            if (s[i-1] == '[') w += 3;
            res[d][w] = '+';
            res[d][w-1] = '-';
            w++;
        }
        h = max(h, d);
    }
    for (int i = h+1; i <= 2*h; ++i)
        for (int j = 0; j < w; ++j)
            res[i][j] = res[2*h-i][j];
    for (int j = 0; j < w; ++j)
        for (int i = 0, k = 0; i <= 2*h; ++i) {
            if (res[i][j] == '+') k ^= 1;
            else if (!res[i][j]) res[i][j] = " |"[k];
        }
    for (int i = 0; i <= 2*h; ++i) cout << res[i] << '\n';
}

int main() {
    fast;
    int t = 1;
    for (int i = 1; i <= t; ++i) solve();
    return 0;
}