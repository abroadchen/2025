/**
n：某种单位数量。
k：组数。
a[N]：每组的需求量。
a1, a2：两种不同容量的"资源"统计变量
不断读入 n 和 k，直到输入结束（多组测试用例）
读入 k 组每组的需求数量 a[i]（比如每组要住的人数 / 需要的餐位）
初始化两种资源：
a1 = n：表示有 n 张"双人床/4人组合的余量"（某种能拆成 4 个座位的基础资源，数量为 n）。
a2 = 2*n：表示有 2n 张"双人座"或通用补位资源
对每组：它可以由若干个 4 人单位拼成。a[i]/4 是这组最多能拆成多少个 4 人单位。
t = min(a[i]/4, a1)：取能用的 4 人单位数（不超过现有的 a1 个 4 人资源）。
a1 -= t：消耗掉用的 4 人单位。
a[i] -= 4*t：从这组需求里扣除已被 4 人单位满足的部分。
目的：优先用 4 人桌满足大的组（贪心——4 人桌最"值"，因为每个 4 人桌对应 a1 单位，且能把 4 个座位打包给同组）
把剩余的没用掉的 4 人资源 a1 升级/转换成 2 人资源。因为 1 个 4 人单位可以变成 2 个 2 人单位，所以 a2 += a1（剩余 n 单位全部转化为 2 人位，加到 a2）。
这是关键贪心：用不完的 4 人桌可以拆成双人座继续用
对剩余需求的每组：a[i]/2 是每组还需要多少个 2 人单位。
t = min(a[i]/2, a2)：用现有的 2 人资源满足。
a2 -= t：消耗 2 人资源。
a[i] -= 2*t：扣除已满足部分
把所有组剩余的未满足需求 a[i] 全部从 a2 里扣除（最后 1 人需求用一个零散座位补齐）。
如果 a2 >= 0，说明资源足够，输出 YES；否则 NO
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 1e4+5;
int n, k, a[N], a1, a2;
int main() {
    fast;
    while (cin >> n >> k) {
        for (int i = 0; i < k; ++i) cin >> a[i];
        a1 = n; a2 = 2*n;
        for (int i = 0; i < k; ++i) {
            int t = min(a[i]/4, a1);
            a1 -= t;
            a[i] -= 4*t;
        }
        a2 += a1;
        for (int i = 0; i < k; ++i) {
            int t = min(a[i]/2, a2);
            a2 -= t;
            a[i] -= 2*t;
        }
        a2 += a1;
        for (int i = 0; i < k; ++i) a2 -= a[i];
        if (a2 >= 0) cout << "YES\n"; else cout << "NO\n";
    }
    return 0;
}