/**
a[i] 只取 1 或 2。要求：在序列中选一个"删除若干元素后"剩下来的子序列，使其形态为

1...1  2...2  1...1  2...2
即至多 4 段、数值为 1,2,1,2 交替（每段可空）。目标是让子序列最长
dp[i][j] 表示考虑前 i 个元素、当前正在填第 j 段（j=0..3）时，能得到的最大长度
第 0 段（全 1）
只能取数值为 1 的元素，所以只能从 dp[i-1][0] 转移，a[i]==1 就 +1。这是前缀中最长的全 1 序列
第 1 段（1...1 2...2）
两种选择：

dp[i][0]：刚进入第 1 段，但这个元素当作 2 不取/或直接从第0段结转——实际上 dp[i][0] 表示"停在 0 段"，把当前元素留给后续；
dp[i-1][1] + (a[i]==2)：继续待在第 1 段，若 a[i]==2 则取它 +1
第 2 段（1...1 2...2 1...1）
从第 1 段结转进来（dp[i][1]），或继续第 2 段取 1
第 3 段（完整 1...1 2...2 1...1 2...2）
从第 2 段结转，或继续第 3 段取 2
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

constexpr int N = 2e3+5;

ll n, a[N], dp[N][5];
int main() {
    fast;
    cin >> n;
    for (int i = 1; i <= n; ++i) cin >> a[i];
    for (int i = 1; i <= n; ++i) {
        dp[i][0] = dp[i-1][0] + (a[i] == 1);
        dp[i][1] = max(dp[i][0], dp[i-1][1] + (a[i] == 2));
        dp[i][2] = max(dp[i][1], dp[i-1][2] + (a[i] == 1));
        dp[i][3] = max(dp[i][2], dp[i-1][3] + (a[i] == 2));
    }
    cout << dp[n][3];
    return 0;
}