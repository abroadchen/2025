/*
*声明字符数组s用于存储输入字符串
声明字符指针p用于遍历字符串
声明三个整型变量：
z：记录字符'0'的个数
o：记录字符'1'的个数
u：记录字符'?'的个数
 *
*p=gets(s)：读取一行字符串到s中，并将p指向字符串开头
*p：循环条件，当当前字符不为'\0'时继续
++p：每次循环后指针向前移动一位
*p==48?++z:*p==49?++o:++u：嵌套三元运算符：
如果*p等于48('0'的ASCII码)，z加1
否则如果*p等于49('1'的ASCII码)，o加1
否则(即为'?')，u加1
 *
*p-- - s：计算字符串长度(此时p指向字符串末尾的'\0')
& 1：按位与1，相当于取模2，得到字符串长度的奇偶性
将结果加到z上
 *如果'0'和'?'的总数比'1'的个数多超过1个，则输出"00"
 *如果'0'和'?'的总数不少于'1'的个数，且'1'和'?'的总数不少于'0'的个数
 *如果最后一个字符是'1'(49)或者最后一个字符是'?'且'0'和'?'比'1'多超过1个，则输出"01"
 *如果最后一个字符是'0'(48)或者最后一个字符是'?'且'1'和'?'比'0'多超过1个，则输出"10"
 *如果'1'和'?'的总数比'0'的个数多超过1个，则输出"11"
 *
 */
#include <cstdio>
using namespace std;

const int N = 102400;
char s[N], *p;
int z, o, u;

int main() {
    for (p=gets(s); *p; ++p) *p==48?++z:*p==49?++o:++u;
    z += p-- - s & 1;
    if (z + u > o + 1) puts("00");
    if (u + z >= o && o + u >= z) {
        if (*p == 49 || *p == '?' && u + z > o + 1) puts("01");
        if (*p == 48 || *p == '?' && o + u > z + 1) puts("10");
    }
    if (o + u > z + 1) puts("11");
    return 0;
}