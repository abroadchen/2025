/**
魔方 6 个面、每面 4 格，共 24 格。输入顺序对应魔方展开图（前、右、上、下、左、后或类似布局）。若当前魔方已还原（每面 4 格同色），输出 YES；否则判断能否通过恰好一次 90° 转动使其还原
读入 24 个格子颜色，x[1..24] 对应魔方展开的 24 个面块
f 判断格子 a,b,c,d 四个颜色全相同。用于检查某面是否同色（面向量由 4 格构成）
代码分成 3 大块，对应魔方三类轴转动（绕 x/y/z 轴旋转某个面），每块又分两种旋转方向
第一块：前面与后面固定
检查"前、后"两面色块顺序是否已同色（f(1,2,3,4) 前面、f(9,10,11,12) 后面），若已同色，则只需转动其它面（上下/左右）把剩余面也统一。
若此时剩余四面通过一次转动能全部同色，则 ok=1。
每个块里的两种方案对应顺时针/逆时针两个转动方向，分别枚举哪个方向的转动能让其它四面同色

 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 25;

int x[N];
bool f(int a, int b, int c, int d) { return x[a]==x[b]&&x[c]==x[d]&&x[a]==x[c]; }

int main() {
    fast;
    for (int i = 1; i <= N; ++i) cin >> x[i];
    bool ok = 0;
    if (f(1,2,3,4)&&f(9,10,11,12)) {
        if (f(5,6,15,16)&&f(17,18,7,8)&&f(21,22,19,20)&&f(13,14,23,24)) ok = 1;
        if (f(13,14,7,8)&&f(5,6,19,20)&&f(17,18,23,24)&&f(21,22,15,16)) ok = 1;
    }
    if (f(13,14,15,16)&&f(17,18,19,20)) {
        if (f(1,3,6,8)&&f(5,7,10,12)&&f(9,11,21,23)&&f(22,24,2,4)) ok = 1;
        if (f(2,4,5,7)&&f(6,8,9,11)&&f(10,12,22,24)&&f(21,23,1,3)) ok = 1;
    }
    if (f(5,6,7,8)&&f(21,22,23,24)) {
        if (f(15,13,3,4)&&f(1,2,17,19)&&f(18,20,10,9)&&f(12,11,16,14)) ok = 1;
        if (f(16,14,1,2)&&f(3,4,18,20)&&f(17,19,12,11)&&f(15,13,10,9)) ok = 1;
    }
    if (ok) cout << "YES\n"; else cout << "NO\n";
    return 0;
}