/**
#define u (i&1)：滚动数组下标。i&1 当 i 为偶数时是 0，奇数时是 1，用来在两层之间交替。
eps = 1e-18：用于判断浮点数是否为 0（防止除零）。
N = 1e4+5：数组大小，足够容纳 n=10000。
inf = 1e6：输入数据单位换算用（输入的概率是整数，要除以 1e6 转成小数）。
double q[2][N]：先验概率数组（滚动数组，2 层）。
double dp[2][N]：期望收益 DP 数组（滚动数组，2 层）
读入 n（球的总数）和 c（单次抽球成本）。
c /= 1e6：把整数形式的成本转成小数（因为输入是以 1e-6 为单位的）
读入初始先验分布 q[n%2][i]。n%2 是初始层（因为 DP 从 i=n-1 倒推到 0，最先用到的层是 (n-1+1)=n 层，即 n&1 层，所以初始数据放在 q[n&1]）。
q[n%2][i] /= 1e6：把概率值转成小数。
先验含义：q[i][j] 表示"在已经抽取了
i
i 个球、且其中有
j
j 个红球的观测下，袋中红球比例的加权/后验度量"
外层循环 i：从 n-1 倒推到 0。i 表示"已经抽取了 i 个球"（反向推进，从抽了 n-1 个球的状态往前推到抽了 0 个球的初始状态）。
内层循环 j：j 表示"这 i 个球中有 j 个是红球"。
之所以 j 上限是 i（而不是 n），是因为已有 i 个球里最多 i 个红球
贝叶斯后验更新，计算当前状态 (i,j) 的先验权重 q[i][j]。

由于是从 i+1 层推到 i 层（即"多抽一个球"之后的状态），逆推回来时有两条来源路径：

路径 A：前一状态是 (i+1, j+1)，即已经抽了 i+1 个球、其中 j+1 个红球；然后"把刚才抽的那个球放回去/回溯"——从 i+1 个球回到 i 个球，如果是红球则 j+1 变 j。从 i+1 个球变 i 个球需要"去掉"一个球，其中红球的概率是 (j+1)/(i+1)（因为 i+1 个球里 j+1 个红球）。
路径 B：前一状态是 (i+1, j)，即已经抽了 i+1 个球、其中 j 个红球；去掉一个白球，概率是 (i+1-j)/(i+1)。
u^1 就是 (i+1)&1，即上一层 i+1 的滚动槽位
如果当前状态的先验权重 q[i][j] 几乎为 0，说明这个状态实际不可能出现（概率为 0），跳过，不计算（避免下一步除零）
计算"下一个球是红球的条件概率" p。

用贝叶斯公式
P(下个球是红球 | 已抽i个、其中j个红)
由上面的路径 A，q[i+1][j+1] 乘上挑选红球的概率 (j+1)/(i+1) 再除以 q[i][j]（归一化）
这其实就是在已知袋中红球比例先验的情况下，下一个抽出的球是红球的概率——这是这题的核心，因为决策就基于这个概率
从状态 (i,j)（已抽 i 个、j 个红），决定是否继续抽，并最大化期望收益：

若继续抽下一个球，成本为 c：
下一个是红球（概率 p）：获得 +1 收益，进入状态 (i+1, j+1)，其后续期望为 dp[u^1][j+1]。合计贡献：(dp[i+1][j+1] + 1) * p
下一个是白球（概率 1-p）：无即时收益，进入状态 (i+1, j)，后续期望 dp[u^1][j]。合计贡献：dp[i+1][j] * (1-p)
再减去本次抽球成本 c：... - c
若不继续抽（停止），收益为 0
max(0, ...) 表示最优策略：要么停止拿 0，要么付成本继续抽。
最终答案：从初始状态 (i=0, j=0)（还没抽球，0 个红球）出发的最大期望收益 dp[0][0]，保留 10 位小数
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define u (i&1)
#define eps 1e-18
using namespace std;
constexpr int N = 1e4+5, inf = 1e6;
int n;
double q[2][N], c, dp[2][N];
int main() {
    fast;
    cin >> n >> c; c/=inf;
    for (int i = 0; i <= n; ++i)
        cin >> q[n%2][i], q[n%2][i]/=inf;
    for (int i = n-1; i >= 0; --i)
        for (int j = 0; j <= i; ++j) {
            double p;
            q[u][j] = 1.0*(j+1)/(i+1)*q[u^1][j+1]+1.0*(i+1-j)/(i+1)*q[u^1][j];
            if (q[u][j] < eps) continue;
            p = q[u^1][j+1]*(j+1)/q[u][j]/(i+1);
            dp[u][j] = max(0.0, dp[u^1][j]*(1-p)+(dp[u^1][j+1]+1)*p-c);
        }
    printf("%.10f", dp[0][0]);
    return 0;
}