/**
N = 1005：字符串最大长度上界。
n：字符串长度，s：字符串本体（char 数组，从下标 0 存）。
读入 n 和字符串 s
遍历相邻对 (i, i+1)：
如果 s[i] 和 s[i+1] 相同，且 s[i] 不是 ?，那么 s[i+1]（也必然相同，因为相等）也不可能是 ? 变来的不同字符——两个相同且确定的连续字符必然违反"相邻不同"，直接输出 No 终止
对每个中间的 ?（i=1..n-2）‍：

若它是 ?，且满足条件 s[i-1] == s[i+1] 或 s[i+1] == '?'，则输出 Yes 并结束
情形 A：s[i+1] == '?'——存在两个连续的 ?。两个相邻 ? 可以分别填成任意两个不同字符（比如填 A、B，且能同时兼顾左右邻居），从而必然能把整串"修正"出来（因为字符集足够大，总能让它们互不相同且与两侧不同）。
情形 B：s[i-1] == s[i+1]——? 的两侧邻居是同一个字符（相等）。此时中间的 ? 只要填一个和两侧都不同的字符（字符集够大一定存在），就能让 i-1, i, i+1 三处都不和邻居冲突。而由于只有这一个 ? 是关键，其他地方要么已经被第二部分的检查保证没有相邻冲突，要么能一并调整。所以有解 → Yes
若 s[0] == '?' 或 s[n-1] == '?'（首或尾是 ?），输出 Yes。因为端点 ? 只需避开一个邻居，一定能找到合适字母，也能"解锁"整串 → 有解。
否则：如果上述"自由 ?"的情况都不存在，说明所有 ? 都是"两面夹紧且两侧不同"的中段 ?，无法靠它们制造自由度，且确定字符部分又必须保证相邻不同——此时若还能完全合法早就在第二部分返回了，这里剩下的就只能填出冲突，故输出 No
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)

using namespace std;

constexpr int N = 1005;

int n;
char s[N];
int main() {
    fast;
    cin >> n >> s;
    for (int i = 0; i < n; ++i)
        if (s[i] == s[i+1] && s[i] != '?') {
            cout << "No\n"; return 0;
        }
    for (int i = 1; i < n-1; ++i)
        if (s[i] == '?') {
            if (s[i-1] == s[i+1] || s[i+1] == '?') {
                cout << "Yes\n"; return 0;
            }
        }
    if (s[0] == '?' || s[n-1] == '?') { cout << "Yes\n"; return 0; }
    cout << "No\n";
    return 0;
}