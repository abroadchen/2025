/**
定义 区间结构体 node ：
- u ：两个相邻负数之间的 间隔大小 （间隔内正数的数量）。
- x ：前一个负数的位置。
- y ：后一个负数的位置。
- operator< ：重载 < 运算符，按间隔 u 升序排序（用于贪心选择最小间隔）。
p[N] ：存储所有相邻负数对的间隔信息
- a[N] ：存储输入的数组。
- n ：数组长度。
- k ：可执行的消除操作次数
- c ：数组中负数的总数。
- l ：上一个负数的位置（初始为0表示未找到）。
- r ：当前负数的位置。
- cnt ：已记录的相邻负数对数量

- 遍历数组每个元素 a[i] 。
- 若当前元素是负数（ a[i] < 0 ）：
  - c++ ：负数计数加1。
  - 若 l == 0 ：这是第一个负数，记录其位置 l = i 。
  - 否则：找到第二个及后续的负数：
    - r = i ：记录当前负数位置。
    - p[cnt++] = {.u = r-l-1, .x = l, .y = r} ：使用C++20的 指定初始化 语法记录间隔信息：
      - u = r-l-1 ：两个负数之间的 正数数量 （间隔大小）。
      - x = l ：前一个负数的位置。
      - y = r ：当前负数的位置。
    - l = r ：将当前负数作为下一个负数的"前一个"。

若负数数量 c 超过操作次数 k ，无法消除所有负数（每次操作至少消除一个负数），输出 -1 并跳过当前用例
若无负数（ c == 0 ），无需任何操作，成本为0，输出 0 并跳过当前用例

计算 最后一个负数到数组末尾的距离 ：
- 若只有一个负数（ r == 0 ）：距离为 n - l （从该负数到末尾的元素数）。
- 若有多个负数：距离为 n - r （从最后一个负数到末尾的元素数）。
这个距离用于后续判断是否需要额外成本处理最后一段
对所有间隔按 间隔大小 u 升序排序 ，便于优先选择最小的间隔进行消除（贪心策略：优先消除成本最低的间隔）
- tmp = k - c ： 剩余可"免费"消除的间隔数 。
- 每消除一个负数至少需要1次操作， c 个负数需要 c 次操作。
- 剩余 k - c 次操作可用于"合并"相邻负数（消除间隔），减少成本。
- res = c * 2 ： 初始总成本 。
- 每个负数的消除成本为2（可能是：消除操作本身+标记成本）。
- 合并间隔可减少成本

- p[i].u <= tmp ：若当前间隔大小不超过剩余操作数 tmp ，则可以消除该间隔。
- 间隔越大，消除成本越高（需要更多操作）。
- 优先消除成本低（间隔小）的间隔。
- tmp -= p[i].u ：扣除消除该间隔所需的操作数。
- res -= 2 ：消除一个间隔可 减少2的总成本 （因为两个相邻负数可以用一次操作消除，而非两次）
- 若剩余操作数 tmp ≥最后一段距离 lst ，则可以 额外减少1的成本 。
- 这是因为最后一段（最后一个负数到数组末尾）可能只需要1的成本（而非2）
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;
constexpr int N = 2e5+5;

struct node {
    int u, x, y;
    bool operator<(const node &o) const {
        return u < o.u;
    }
} p[N];

int a[N], n, k;
int main() {
    fast;
    while (cin >> n >> k) {
        int c = 0, l = 0, r = 0, cnt = 0;
        for (int i = 1; i <= n; ++i) {
            cin >> a[i];
            if (a[i] < 0) {
                c++;
                if (l == 0) l = i;
                else {
                    r = i;
                    p[cnt++] = {.u = r-l-1, .x = l, .y = r};
                    l = r;
                }
            }
        }
        if (c > k) { cout << "-1" << '\n'; continue; }
        if (c == 0) {
            cout << "0" << '\n'; continue;
        }
        int lst = r == 0 ? n - l : n - r;
        sort(p, p + cnt);
        int tmp = k - c, res = c * 2;
        for (int i = 0; i < cnt; ++i) {
            if (p[i].u <= tmp) {
                tmp -= p[i].u;
                res -= 2;
            }
        }
        if (tmp >= lst) res -= 1;
        cout << res << '\n';
    }
    return 0;
}