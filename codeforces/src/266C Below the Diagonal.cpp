/*
*n: 矩阵大小
x[N], y[N]: 存储输入的位置坐标
a[N], b[N], c[N]: 存储操作步骤
x[N]: 存储每个1的行坐标
y[N]: 存储每个1的列坐标
a[N]: 存储操作类型（1表示行交换，2表示列交换）
b[N]: 存储第一个操作对象
c[N]: 存储第二个操作对象
cnt: 操作计数器，初始为0
 *
*对于第i个位置(1-indexed)：
检查行坐标x[i]是否等于期望值i + 1
如果不相等：
遍历后续位置，交换相关的行坐标值
记录行交换操作：类型1，交换行x[i]和行i + 1
操作计数器cnt增加
*检查列坐标y[i]是否大于i
如果是：
遍历后续位置，交换相关的列坐标值
记录列交换操作：类型2，交换列y[i]和列i
操作计数器cnt增加
 *
*输出操作步骤总数
输出每一步操作的详细信息
 *
 *主循环，处理每个位置i（从1到n-1）
*检查第i个1的行坐标是否正确：
期望第i个1位于第(i+1)行（因为索引从1开始）
如果当前行坐标x[i]不等于期望值i + 1，则需要调整
 *内层循环，检查后续的所有位置j（从i+1到n-1）
*如果第j个1当前正好在目标行i + 1上：
将其行坐标改为x[i]（即原来第i个1所在的行）
这模拟了交换行x[i]和行i + 1的效果
*否则如果第j个1在第i个1原来的行x[i]上：
将其行坐标改为i + 1（即目标行）
这也模拟了同样的行交换效果
*a[cnt] = 1: 操作类型为1（行交换）
b[cnt] = x[i]: 交换的第一个行号
c[cnt] = i + 1: 交换的第二个行号（目标行）
cnt++: 操作计数器自增
 *
*检查第i个1的列坐标是否需要调整：
期望第i个1位于第i列或更前面的列
如果当前列坐标y[i]大于i，则需要调整列
 *内层循环，检查后续的所有位置j（从i+1到n-1）
*如果第j个1当前在第i列：
将其列坐标改为y[i]（即原来第i个1所在的列）
这模拟了交换列y[i]和列i的效果
*
否则如果第j个1在第i个1原来的列y[i]上：
将其列坐标改为i（即目标列）
这也模拟了同样的列交换效果
*a[cnt] = 2: 操作类型为2（列交换）
b[cnt] = y[i]: 交换的第一个列号
c[cnt] = i: 交换的第二个列号（目标列）
cnt++: 操作计数器自增
 *
 *
 */
#include <iostream>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define N 100005
using namespace std;

int main() {
    fast;
    int n, x[N], y[N], a[N], b[N], c[N], cnt = 0; cin >> n;
    for (int i = 1; i < n; ++i) cin >> x[i] >> y[i];//矩阵中值为1的位置
    for (int i = 1; i < n; ++i) {
        if (x[i] != i + 1) {//索引从1开始
            for (int j = i + 1; j < n; ++j) {
                if (x[j] == i + 1) x[j] = x[i];//如果第j个1在目标行(i+1)，则把它移到x[i]行
                else if (x[j] == x[i]) x[j] = i + 1;//如果第j个1在x[i]行，则把它移到目标行(i+1)
            }
            a[cnt] = 1, b[cnt] = x[i], c[cnt++] = i + 1;
        }
        if (y[i] > i) {
            for (int j = i + 1; j < n; ++j) {
                if (y[j] == i) y[j] = y[i];
                else if (y[j] == y[i]) y[j] = i;
            }
            a[cnt] = 2, b[cnt] = y[i], c[cnt++] = i;
        }
    }
    cout << cnt << '\n';
    for (int i = 0; i < cnt; ++i) cout << a[i] << ' ' << b[i] << ' ' << c[i] << '\n';
    return 0;
}