/*
*定义常量：maxn=20（最大点数），maxt=10（最大驼峰数）
声明变量n（点数）和t（驼峰数）

定义四维DP数组：
第一维：位置i（1到n）
第二维：驼峰数量j（0到t）
第三维：当前y坐标（这里用0-3表示1-4）
第四维：趋势状态（0表示下降，1表示上升）
 *
* 初始化边界条件（第2个点）：
f[2][0][4][0]=3：第2点y=5(数组中4)，下降趋势，0个驼峰，有3种可能的前一点(y=4,3,2)
f[2][0][3][0]=2：第2点y=4(数组中3)，下降趋势，0个驼峰，有2种可能的前一点(y=3,2)
f[2][0][2][0]=1：第2点y=3(数组中2)，下降趋势，0个驼峰，有1种可能的前一点(y=2)

四重循环：
i：当前位置（从3到n）
j：当前驼峰数（从0到t）
k：当前点的y坐标（1到4，对应数组索引0-3，但这里直接用1-4）
l：前一点的y坐标（1到4）

如果前一点l小于当前点k（上升趋势）：
更新状态f[i][j][k][0]（注意这里是0，表示从上升转为下降）
累加前一状态f[i-1][j][l][0]和f[i-1][j][l][1]的值

如果前一点l大于当前点k（下降趋势）：
更新状态f[i][j][k][1]（注意这里是1，表示继续保持下降）
累加前一状态f[i-1][j][l][1]的值
如果j>0，还加上f[i-1][j-1][l][0]（表示在前一点形成了新驼峰）

计算最终答案：
遍历最后一个点的所有可能y坐标（1到4）
累加f[n][t][i][1]（最后一点处于下降趋势且有t个驼峰的状态数）
 */







#include <cstdio>
using namespace std;
const int maxn=20, maxt=10;
int n, t;
int f[maxn+5][maxt+5][4][2];

int main() {
    scanf("%d %d", &n, &t);
    f[2][0][4][0]=3;
    f[2][0][3][0]=2;
    f[2][0][2][0]=1;

    for (int i = 3; i <= n; ++i)
        for (int j = 0; j <= t; ++j)
            for (int k = 1; k <= 4; ++k)
                for (int l = 1; l <= 4; ++l) {
                    if (l < k) f[i][j][k][0] += f[i-1][j][l][0] + f[i-1][j][l][1];
                    if (l > k) f[i][j][k][1] += f[i-1][j][l][1] + (j>0?f[i-1][j-1][l][0]:0);
                }
    int ans = 0;
    for (int i = 1; i <= 4; ++i)
        ans += f[n][t][i][1];
    printf("%d\n", ans);
    return 0;
}