/**
f[i][j]：稀疏表。表示从下标 i 开始、连续长度 2^j 这一段内所有元素的乘积对 m 取模。
pw[j] = 2^j，用于快速定位区间
用二进制分解（贪心从大段往小段）把区间 [l, r] 拆成若干段 2^j 长度的块，逐块连乘取模。
因为模是 m，若某一段乘积为 0，最终 res 也为 0 → 返回 0（真值假）。返回 res，while 靠它判断。
由于块与块之间无重叠（l += pw[j] 前进），连乘结果恰好等于整个区间所有元素乘积 % m（乘积的模可以逐段算，乘法结合律保证正确
f[i][0] 即长度为 2^0 = 1 的段，也就是第 i 个元素本身，读入时直接取模保存
预计算每个数的 log2 下取整（lg）。不过本代码的 get 用的是 pw 从大到小枚举而非 lg，所以 lg[] 在本段其实并未被实际使用，属于预计算但闲置的数组
预计算 2^0 ... 2^20
建稀疏表：f[i][j] = product(前半个 2^{j-1} 段) * product(后半个 2^{j-1} 段) % m。
f[i][j-1] 是 [i, i+2^{j-1}-1]，f[i+pw[j-1]][j-1] 是 [i+2^{j-1}, i+2^j-1]，两者拼接正好是 [i, i+2^j-1]
外层 i 是左端点，r 是当前右端点（单调不降，这就是双指针的正确性来源）。
内层 while (r <= n && get(i, r))：get(i, r) 返回「[i, r] 的乘积 % m」。
只要结果非 0（真值），说明还没构成 0 区间，就把 r 往右推。
当 get(i, r) == 0（假值）时循环停：此时 [i, r] 的乘积 % m == 0，r 就是最小的合法右端点（因为是从左往右单调试探出来的）。
ans += n - r + 1：r, r+1, ..., n 都是合法右端点，共 n-r+1 个。
关键边界：r 只增不减，因为左端点 i 右移后，之前使 [i, r] 含 0 的 r 对 i+1 也必然含 0（去掉左边元素不会"丢失" 0 因子）？—— 关于这点要小心，见下方注意事项。
为何 r 能单调不回头（双指针成立）‍：如果 [i, r] 乘积 % m == 0，那么对更大的 i'（左端点右移），[i', r] 是 [i, r] 的后缀。但乘积 % m 为 0 的区间去掉前缀后，剩下的后缀乘积不一定仍为 0（可能把"含 m 因子"的那部分元素去掉了）。因此严格来说这里的 r 单调性需要题目数据保证或另有依据——如果 m 很大、0 的出现不具单调性，那么这个双指针可能是错的。这一点要提醒：该双指针写法成立常见于题目保证元素非负/或保证乘积 0 具有单调性（如 m 为某个质数、元素值大的情况）。需结合具体题目约束判断。
实际上更稳妥的经典做法是：左端点 i 递增时，右端点从"上一轮结果"继续，其正确性依赖于"若 [i,r] 乘积 mod m == 0，则 [i+1, r'] 在 r'≤原r 的某个范围内必也有解"——这在本题设定下是否成立取决于 m 的性质，代码默认成立。

建稀疏表：O(n log n)。
双指针：i 和 r 各至多移动 n 次，加上每次 get 的 O(log n)，总 O(n log n)。
空间：f 为 N × 22，约 O(n log n)
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;

constexpr int N = 1e5+50;
int pw[22], f[N][22], m;
int get(int l, int r) {
    int res = 1;
    for (int j = 20; j >= 0; --j)
        if (l + pw[j] - 1 <= r)
            res = 1ll*res*f[l][j]%m, l += pw[j];
    return res;
}

int n, lg[N];
void solve() {
    cin >> n >> m;
    for (int i = 1; i <= n; ++i) cin >> f[i][0], f[i][0] %= m;
    lg[1] = 0;
    for (int i = 2; i <= n; ++i) lg[i] = lg[i>>1]+1;
    pw[0] = 1;
    for (int i = 1; i <= 20; ++i) pw[i] = pw[i-1]<<1;
    for (int j = 1; j <= 20; ++j)
        for (int i = 1; i <= n-pw[j]+1; ++i)
            f[i][j] = 1ll*f[i][j-1]*f[i+pw[j-1]][j-1]%m;
    int r = 1; ll ans = 0;
    for (int i = 1; i <= n; ++i) {
        while (r <= n && get(i, r)) ++r;
        ans += n - r + 1;
    }
    cout << ans << '\n';
}

int main() {
    fast;
    int t = 1;
    while (t--) solve();
    return 0;
}