/**
n：元素个数；k：模数；v：目标值。
a[i]：读入后存 原数 % k（即余数）。
b[i]：原值（未取模）。
sum：所有数总和。
dp[i][j]：01 背包可行性表。dp[i][j] 表示用前 i 个数（每个数或取或不取其"余数部分"）能否凑出模 k 下的和 j。
值为 1：不取第 i 个数也能凑出 j（沿用 dp[i-1][j]）；
值为 2：取第 i 个数的余数 a[i] 后凑出 j（新增方案）。
f[N]：标记第 i 个数是否被选入"凑余数 v%k"的那一组（用于后续构造，f[i]=1 表示 i 被选中）
读入 a[i]，先把原值存入 b[i]，再把 a[i] 取模 k（存余数）。
累计 sum（原值总和）。
可行性剪枝：若总和 sum < v，一组总和不可能达到 v，直接 NO。【关键前提：操作只能转移 k 的整数倍，不能凭空造值，所以某组总和有上界】
dp[0][0]=1：空集可凑出余数 0。
对每个数 i、每个已可达余数 j：
不取 i：dp[i][j]=1；
取 i（加上其余数 a[i]）：dp[i][(j+a[i])%k]=2。
结果通过 dp[n][*] 表达用全部 n 个数能否凑出任一余数。
目标余数是 num = v%k。若 dp[n][num]==0 说明凑不出该余数 → NO（因为转移 k 的整数倍无法改变余数，凑不到 v 的余数就没戏）。
为什么背包余数可行 == 操作可行：因为操作"每次转移 k 的整数倍"不改变整组余数和；要得到总和 v，整组余数和必须 ≡ v (mod k)。若能选出若干数的余数凑成 v%k，剩下的 (v - 所选余数和) 恰是 k 的整数倍，即可通过转移补足
从后往前回溯背包路径：若 dp[i][num]==2，说明"取第 i 个数的余数"构成了当前路径，标记 f[i]=1，把 num 减去 a[i] 继续回溯；记录的 ans 累计这些被选数的原值总和。
找到两个"代表点"：
x1：第一个被选中的位置（f[i]=1 的某个索引），作为目标组 A 的代表桶。
x2：第一个未被选中的位置（且 x2 初见时赋），作为另一组 B 的代表桶。
这两个索引分别代表"要凑成 v 的那组"和"另一组"，后续转移都以它们为汇点/源点
当 x1==-1：说明凑余数不需要特殊选数（或 v 是 k 倍数），直接把前 n-1 个非零元素全部转移到第 n 个桶（每次转移 ceil(b[i]/k) 份 k），把值集中到 n。再判断若 v/k>0，从 n 转 v/k 份 k 给 1。(b[i]+k-1)/k 是向上取整 b[i]/k（把 b[i] 全转走所需的 k 份数）
一般情况（有选中组、有代表桶 x1/x2）：
初始化两代表桶的当前和 s1=b[x1]、s2=b[x2]。
遍历所有非代表、非零元素：
若该元素未被选中（!f[i] → 属于"另一组 B"）：把它的全部（ceil(b[i]/k) 份）转移到代表桶 x2 汇合，更新 s2。
若被选中（f[i] → 属于"目标组 A"）：转移到代表桶 x1，更新 s1。
这样把两组各自合并到 x1、x2 两个桶。
现在目标组 A（汇聚在 x1）已有和 s1，需要补/减 v - s1 到恰好 v。由于是 k 的倍数，cnt = (v-s1)/k 为整数：
cnt>0：还差，从 B 组代表 x2 转移 cnt 份 k 给 x1。
cnt<0：多了，从 x1 转 -cnt 份 k 出去（到另一个桶，此处用 x1==1?2:1 选个非 x1 的可转目标，一般转到与 x1 不同的桶，因为 A 组已与其他桶分离）。
输出这些"转移 k 的整数倍"的操作，保证最终 x1 组总和恰为 v

1 表示沿用上一步、2 表示"此处取第 i 个数是新方案"，回溯时靠 ==2 识别"是否选了 i"
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)

using namespace std;

constexpr int N = 5e3+5;

int n, k, v, sum, a[N], b[N], dp[N][N], f[N];
int main() {
    fast;
    cin >> n >> k >> v;
    for (int i = 1; i <= n; ++i) {
        cin >> a[i]; b[i] = a[i]; a[i] %= k;
        sum += b[i];
    }
    if (sum < v) { cout << "NO\n"; return 0; }
    dp[0][0] = 1;
    for (int i = 1; i <= n; ++i)
        for (int j = 0; j < k; ++j)
            if (dp[i-1][j]) {
                dp[i][j] = 1;
                if (!dp[i][(j+a[i])%k])
                    dp[i][(j+a[i])%k] = 2;
            }
    int num = v%k;
    if (!dp[n][num]) { cout << "NO\n"; return 0; }
    cout << "YES\n";
    int x1 = -1, x2 = -1, ans = 0;
    for (int i = n; i >= 1; --i) {
        if (dp[i][num] == 2) {
            f[i] = 1;
            num = (num - a[i] + k) % k;
            ans += b[i];
            if (x1 == -1) x1 = i;
        } else if (x2 == -1) x2 = i;
    }
    if (x1 == -1) {
        for (int i = 1; i < n; ++i)
            if (b[i]) cout << (b[i]+k-1)/k << ' ' << i << ' ' << n << '\n';
        if (v/k) cout << v/k << ' ' << n << ' ' << 1 << '\n';
        return 0;
    }
    int s1 = b[x1], s2 = b[x2];
    for (int i = 1; i <= n; ++i) {
        if (i == x1 || i == x2 || !b[i]) continue;
        if (!f[i]) {
            cout << (b[i]+k-1)/k << ' ' << i << ' ' << x2 << '\n';
            s2 += b[i];
        } else {
            cout << (b[i]+k-1)/k << ' ' << i << ' ' << x1 << '\n';
            s1 += b[i];
        }
    }
    int cnt = (v - s1)/k;
    if (cnt > 0) cout << cnt << ' ' << x2 << ' ' << x1 << '\n';
    else if (cnt < 0) cout << -cnt << ' ' << x1 << ' ' << (x1==1?2:1) << '\n';
    return 0;
}