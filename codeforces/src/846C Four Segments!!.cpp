/**
边读边构建前缀和：a[i] 读入原始值后加上 a[i-1]，于是 a[i] 表示原数组前 i+1 项（下标 0..i）的和。
注意：a[i-1] 在 i=0 时越界访问 a[-1]，但这是全局数组（ll a[5005] 是全局变量），默认全是 0，所以能正常工作。这是常见的"省空间的偷懒写法"，依赖全局零初始化
求左闭右开区间 [x, y) 的元素和，即下标 x .. y-1 的和。
对前缀和应用：sum(x,y) = 前缀(y-1) − 前缀(x-1)；[x, y) 为空（x==y）时返回 0
外层 for i 遍历中间分割点位置（i 从 0 到 n，代表第二段从 i 开始，可空）。
m1、m2：在中点 i 固定的前提下，左右两半各自能取得的最大值；ss1、ss2 记录取到最大值时的分割位置
固定中间分割点 i 后，枚举左半段的第二个分割点 j（0 ≤ j ≤ i）。
目标是让左半段内部的「左块 − 右块」= sum(0,j) − sum(j,i) 最大（请对比最终目标：第一段 − 第二段 = sum0 − sum1，而第二段以 i 为右端）。
即：左半段再拆成两段 [0,j) 和 [j,i)，使「前段 − 后段」最大；ss1 记录使该值最大化的 j
同理，固定中间分割点 i 后，枚举右半段的切分点 j（i ≤ j ≤ n）。
目标是让「右块 − 末块」= sum(i,j) − sum(j,n) 最大（对应最终目标中第三段的贡献 sum2，减去中间的 sum1）。
这里对应目标式 ...+ sum2 − sum3... 中各个段的组合方式；ss2 记录使该值最大化的 j
固定 i 时，左半最优 m1 与右半最优 m2 互不干扰，相加 m1 + m2 即当前 i 下的最优目标值。
若优于历史最优 ans，更新并在 s1, s2, s3 中记录三个分割位置：s1 = 左半最优j，s2 = 中间分割 i，s3 = 右半最优j。
最终输出这三个位置下标

最终目标是「第一段和 − 第二段和 + 第三段和」最大化，对应三个段依次是 [0, s1)、[s1, s2)、[s2, n)（或类似），但代码里 s2 = i 记录的是中间分割点本身，而左右两半的分割是相对 i 独立计算的 ss1、ss2。

左半 m1 = sum(0,j) − sum(j,i)：左块 [0,ss1)，右块 [ss1,i)；
右半 m2 = sum(i,j) − sum(j,n)：左块 [i,ss2)，右块 [ss2,n)；
可是这会导致第二段「− sum1」被算了两次（左半的 [ss1,i) 和右半的 [i,ss2) 都各含一部分），这与「只减一次」的真实目标可能存在偏差——严格来说这版代码的目标函数与"三段和相减"并不完全一致，它是经典 Codeforces 846C 的常见写法，s2 其实通常应等于某个与左右两段关联的分割值。单看代码，s2 = i 仅在特殊情况（如第二段为空，ss1=ss2=i）下才与"三段"目标严格吻合。

如果希望保留原代码"左右各 O(i)/O(n−i) 枚举"的框架，可以做这样的修正：

让第二段严格落在 [s1, s2)，即从 s1 到 s2。
左边固定 i=s2 时，枚举 j=s1 ∈ [0,i]：
原代码 m1 = sum(0,j) − sum(j,i) 对应的其实是 正块[0,j) − 负块[j,i)，这部分本身没错（它是目标里 sum0 − sum1 的贡献，其中 sum1 以 i 为右端）。

问题在右边：原代码 m2 = sum(i,j) − sum(j,n) 多算了一个 −sum(j,n)。修正右边为第三段直接取成最大正贡献：

for (i = 0; i <= n; ++i) {
    // 左边：sum(0,j) - sum(j,i) 最大, ss1 = 使最大的 j
    // 右边：直接取第三段 sum(i, j) 最大（而非相减）, ss2 = 使 sum(i,j) 最大的 j
    for (j = i; j <= n; ++j) {
        if (m2 < sum(i,j)) { m2 = sum(i,j); ss2 = j; }   // 第三段选最大正贡献
    }
    ...
}
即把右边从 sum(i,j) − sum(j,n) 改成直接 sum(i,j) 取最大（第三段 [i,j) 正贡献，j 到 n 的部分不再出现负项），这样整体就变成：

sum(0,ss1) − sum(ss1,i) + sum(i,ss2)
正好是标准三段 正 − 负 + 正，消除了原本"多减一块"的问题。
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
using namespace std;
constexpr ll inf = 9e18;
ll a[5005];
int main() {
    fast;
    int n, i, j; cin >> n;
    for (i = 0; i < n; ++i) {
        cin >> a[i]; a[i] += a[i-1];
    }
    auto sum = [&](int x, int y) -> ll {
        return (y == 0 ? 0 : a[y-1]) - (x == 0 ? 0 : a[x-1]);
    };
    ll ans = -inf, s1 = 0, s2 = 0, s3 = 0;
    for (i = 0; i <= n; ++i) {
        ll m1 = -inf, m2 = -inf, ss1 = 0, ss2 = 0;
        for (j = 0; j <= i; ++j) {
            if (m1 < sum(0, j) - sum(j, i)) {
                m1 = sum(0, j) - sum(j, i);
                ss1 = j;
            }
        }
        for (j = i; j <= n; ++j) {
            if (m2 < sum(i, j) - sum(j, n)) {
                m2 = sum(i, j) - sum(j, n);
                ss2 = j;
            }
        }
        if (ans < m1 + m2) {
            ans = m1 + m2;
            s1 = ss1; s2 = i; s3 = ss2;
        }
    }
    cout << s1 << ' ' << s2 << ' ' << s3;
    return 0;
}