/**
m: 中间位置变量
g1, g2: 记录状态转移路径的三维数组
f: DP状态数组，记录是否可达
s: 输入字符串
t: 输出结果字符串

长度为n的字符串是否能构造出目标串，k表示初始状态

如果n为奇数，初始化中心位置m的状态
遍历可能的数字i(0,2,4...18)，检查是否满足条件
如果n为偶数，初始化中间两个位置的状态
检查相邻两位是否匹配

从外向内填充DP表
考虑四种情况：当前字符对可能是(j,j), (j,j+1), (j+1,j), (j+1,j+1)
每种情况对应不同的状态转移
如果起始状态不可达，返回false
根据记录的路径重构答案
(g1[i][k0][k1] + 1)/2 和 g1[i][k0][k1]/2 分别得到左右两半的数字
g2数组记录状态转移方向，用于回溯

2|k0 的结果总是在高位（第1位）设置为1
同时保留了 k0 的原始值在低位（第0位）
编码后的值：2|0=2 或 2|1=3
解码过程
高1位（右移后）代表一个状态信息 k0
低1位（与1按位与）代表另一个状态信息 k1

进位机制：
对于小的 i 值（0-9），结果为0
对于大的 i 值（10-18），结果为1
 */
#include <bits/stdc++.h>
using namespace std;
constexpr int N = 1e5+5, M = 10;

int m, g1[N][2][2], g2[N][2][2];
bool f[N][2][2];
char s[N], t[N];
bool ok(int n, int k) {
    int i, j, k0, k1; m = (n+1)>>1;
    for (i = 0; i <= n; ++i)
        for (k0 = 0; k0 < 2; ++k0)
            for (k1 = 0; k1 < 2; ++k1)
                f[i][k0][k1] = g1[i][k0][k1] = g2[i][k0][k1] = 0;
    if (n&1) {
        for (i = 0; i < 19; i += 2) if (s[m] == i%M) {
            f[m][i/M][0] = true;
            g1[m][i/M][0] = i;
        } else if (s[m] == (i+1)%M) {
            f[m][(i+1)/M][1] = true;
            g1[m][(i+1)/M][1] = i;
        }
    } else {
        for (i = 0; i < 19; i++) {
            if (s[m] == i%M && s[m+1] == (i+i/M)%M) {
                f[m][(i+i/M)/M][0] = true;
                g1[m][(i+i/M)/M][0] = i;
            } else if (s[m] == (i+1)%M && s[m+1] == (i+(i+1)/M)%M) {
                f[m][(i+(i+1)/M)/M][1] = true;
                g1[m][(i+(i+1)/M)/M][1] = i;
            }
        }
    }
    for (i = m-1; i > 0; i--)
        for (j = 0; j < 19; j++) {
            k0 = j/M; k1 = (j+1)/M;
            if (s[i] == j%M && s[n-i+1] == j%M && f[i+1][0][k0]) {
                f[i][k0][0] = true;
                g1[i][k0][0] = j; g2[i][k0][0] = k0;
            }
            if (s[i] == j%M && s[n-i+1] == (j+1)%M && f[i+1][1][k0]) {
                f[i][k1][0] = true;
                g1[i][k1][0] = j; g2[i][k1][0] = 2|k0;
            }
            if (s[i] == (j+1)%M && s[n-i+1] == j%M && f[i+1][0][k1]) {
                f[i][k0][1] = true;
                g1[i][k0][1] = j; g2[i][k0][1] = k1;
            }
            if (s[i] == (j+1)%M && s[n-i+1] == (j+1)%M && f[i+1][1][k1]) {
                f[i][k1][1] = true;
                g1[i][k1][1] = j; g2[i][k1][1] = 2|k1;
            }
        }
    if (!f[1][k][0]) return false;
    for (i = 1, k0=k, k1=0; i <= m; i++) {
        t[i] = (g1[i][k0][k1] + 1)/2 + 48;
        t[n-i+1] = g1[i][k0][k1]/2 + 48;
        j = k0;
        k0 = g2[i][j][k1]>>1, k1 = g2[i][j][k1]&1;
    }
    return t[1] != 48;
}

int main() {
    int i, n = 0; scanf("%s", s + 1);
    for (i = 1; s[i]; i++) n++, s[i] ^= 48;//将字符转换为数字
    for (i = 1; i <= n-i; i++) {//反转字符串
        char c = s[i];
        s[i] = s[n-i+1];
        s[n-i+1] = c;
    }
    //尝试以0开头的情况
    if (ok(n, 0)) {
        printf("%s\n", t + 1);
        return 0;
    }
    //如果失败且最后一位是1，则尝试以1开头，长度减1的情况
    if (s[n] == 1 && ok(n-1, 1)) printf("%s\n", t + 1);
    else puts("0");
    return 0;
}