/*
*f[N]: 斐波那契数列，f[i]表示第i层斐波那契树的节点数
d[N]: 深度相关信息
dfs函数计算从节点x到第g层斐波那契树两个特殊节点的距离：
a1[g]: 从x到左子树根节点的距离
a2[g]: 从x到右子树根节点的距离
 *
*d1,d2,d3,d4: 距离数组，存储中间计算结果
dfs2函数计算第g层斐波那契树上节点x到节点y的最短距离
 *
*f[0]=1, f[1]=2: 基础情况
f[i] = f[i-1] + f[i-2]: 斐波那契递推关系
d[i] = d[i-2] + 1: 深度递推关系
 *
*x: 目标节点编号
g: 当前处理的层数
a1, a2: 指向两个数组的指针，用于存储距离结果
*当层数g为0时
设置a1[0]和a2[0]都为0（第0层只有一个节点）
*当层数g为1时
a1[1] = x == 2: 如果x等于2，则a1[1]为1(真)，否则为0(假)
a2[1] = x == 1: 如果x等于1，则a2[1]为1(真)，否则为0(假)
 *如果目标节点x在左子树范围内（小于等于左子树节点数f[g-1]）
 *递归调用，处理左子树（层数减1）
*计算到左子树根节点的距离：
取从x到左子树中两个特殊点的较小距离
a2[g-1]+2: 通过右子树绕路到左子树需要额外2步
*计算到右子树根节点的距离：
从左子树到右子树需要经过根节点，额外1步
加上右子树的深度偏移量d[g-2]
 *否则，目标节点x在右子树中
*递归调用，处理右子树：
节点编号调整为相对于右子树的编号(x - f[g-1])
层数减少2级
*计算到左子树根节点的距离：
从右子树到左子树需要1步
加上右子树内部到其根的距离a1[g-2]
 *计算到右子树根节点的距离：直接等于右子树内部的距离a2[g-2]
 *
 *
*g: 当前层数
x, y: 两个目标节点
*当层数≤1时
如果x≠y返回1（不同节点距离为1）
如果x=y返回0（相同节点距离为0）
*如果两个节点都在左子树中：
递归计算左子树内距离dfs2(g-1, x, y)
或者通过左右子树间路径：min(d1[g-1] + d4[g-1], d2[g-1] + d3[g-1]) + 2
取两者较小值
*如果x在左子树，y在右子树：
从左子树到右子树的最短路径
min(d1[g-1], d2[g-1]): 左子树内到连接点的最短距离
+1: 跨越到右子树
+d3[g-2]: 右子树内的偏移量
*否则两个节点都在右子树中：
递归计算右子树内距离
调整节点编号为相对右子树的编号
 *
 *
*f[0]=1: 第0层有1个节点
f[1]=2: 第1层有2个节点
d[0]=0: 第0层深度偏移为0
d[1]=1: 第1层深度偏移为1
 */
#include <iostream>
#include <algorithm>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
#define ll long long
#define N 1005
#define M 80
using namespace std;

ll f[N], d[N];
void dfs(const ll x, const ll g, ll *a1, ll *a2) {
    if (!g) { a1[g] = a2[g] = 0; return; }
    if (g == 1) { a1[g] = x == 2, a2[g] = x == 1; return; }
    if (x <= f[g-1]) {
        dfs(x, g - 1, a1, a2);
        a1[g] = min(a1[g-1], a2[g-1]+2);
        a2[g] = min(a1[g-1], a2[g-1]) + 1 + d[g-2];
    } else {
        dfs(x - f[g-1], g - 2, a1, a2);
        a1[g] = a1[g-2] + 1;
        a2[g] = a2[g-2];
    }
}

ll d1[N], d2[N], d3[N], d4[N];
ll dfs2(const ll g, const ll x, const ll y) {
    if (g <= 1) return x != y;
    if (x <= f[g-1] && y <= f[g-1]) return min(dfs2(g-1, x, y),
        min(d1[g-1] + d4[g-1], d2[g-1] + d3[g-1]) + 2);
    if (x <= f[g-1] && y > f[g-1]) return min(d1[g-1], d2[g-1]) + 1 + d3[g-2];
    return dfs2(g-2, x - f[g-1], y - f[g-1]);
}


int main() {
    fast;
    f[0] = 1, f[1] = 2, d[0] = 0, d[1] = 1;
    for (ll i = 2; i < M; ++i) f[i] = f[i-1]+f[i-2], d[i] = d[i-2]+1;
    ll m, n; cin >> m >> n; n = min(n, static_cast<ll>(M));
    while (m--) {
        ll x, y; cin >> x >> y;
        if (x > y) swap(x, y);
        dfs(x, n, d1, d2);//分别计算x和y到特殊节点的距离 结果存储在d1和d2中
        dfs(y, n, d3, d4);
        cout << dfs2(n, x, y) << '\n';//计算最短路径
    }
    return 0;
}