/*
*提取小时部分：将字符串前两位字符转换为整数
s[0]-'0'将字符转为数字，乘以10作为十位，加上个位数字
*提取分钟部分：将字符串第4、5位字符转换为整数（跳过冒号）
同样方法将字符转换为数值
 *保存原始时间值，用于后续比较
 *
*回文时间条件：小时的十位等于分钟的个位，且小时的个位等于分钟的十位
或者当前时间仍为初始时间，则继续寻找下一个回文时间
 *
 *
 *如果小时的十位是0（即小时是个位数），则添加前导零
 *将小时转换为字符串并添加到结果中
 *添加时间分隔符冒号
 *如果分钟的十位是0（即分钟是个位数），则添加前导零
 *将分钟转换为字符串并添加到结果中
 *
 *
 */
#include <iostream>
using namespace std;

int main() {
    cin.tie(0)->sync_with_stdio(false);
    string s; cin >> s;
    int h = (s[0] - '0') * 10 + (s[1] - '0'),
    m = (s[3] - '0') * 10 + (s[4] - '0'),
    h1 = h, m1 = m;

    while (h / 10 != m % 10 or h % 10 != m / 10 or
        h == h1 and m == m1) {
        m++;
        if (m == 60) {
            m = 0;
            h++;
            if (h == 24) h = 0;
        }
    }

    string res;
    if (h / 10 == 0) res += '0';
    res += to_string(h);
    res += ':';
    if (m / 10 == 0) res += '0';
    res += to_string(m);
    cout << res;
    return 0;
}