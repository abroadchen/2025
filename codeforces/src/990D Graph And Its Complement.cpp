    if (a != 1 && b != 1 || a == 1 && b == 1 && n <= 3 && n >= 2 || a > n || b > n) {
        cout << "NO\n"; return 0;
    }
    cout << "YES\n";
    if (b != 1) swap(a, b), swap(c, c2);
