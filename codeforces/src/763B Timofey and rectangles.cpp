/**
n 表示后续有多少组数据需要处理；a, b, c, d 通常用于存储四个整数（如坐标、区间端点等）
直接输出 `"YES"`：这通常是题目要求的固定前缀或状态指示（如“答案存在”或“满足条件”）
**abs(a) & 1**：取 `a` 的绝对值后，与 `1` 做位运算 `&`，本质上是获取 `a` 的奇偶性。
    *   如果 `a` 为奇数，则结果为 `1`。
    *   如果 `a` 为偶数，则结果为 `0`。
*   **2 * (abs(a) & 1)**：将 `a` 的奇偶性乘以 `2`，即：
    *   `a` 为奇数时贡献 `2`。
    *   `a` 为偶数时贡献 `0`。
*   **(abs(b) & 1)**：同理，获取 `b` 的奇偶性（奇数为 `1`，偶数为 `0`）。
*   **+ 1**：最终整体加上 `1`，确保输出范围在 `[1, 4]` 之间。
*   **综合公式**：`2*(a%2) + (b%2) + 1`
    *   当 `a` 偶、`b` 偶 → `1`
    *   当 `a` 偶、`b` 奇 → `2`
    *   当 `a` 奇、`b` 偶 → `3`
    *   当 `a` 奇、`b` 奇 → `4`
 */
#include <bits/stdc++.h>
#define fast ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0)
using namespace std;


int main() {
    fast;
    int n, a, b, c, d; cin >> n;
    cout << "YES\n";
    while (n--) {
        cin >> a >> b >> c >> d;
        cout << 2*(abs(a)&1)+(abs(b)&1)+1 << '\n';
    }
    return 0;
}