/*
 *n(矩阵大小)和k(计数器)
 *s[N]: 字符数组，用于读取输入字符串
 *a[N][N] 二维布尔数组，存储输入的01矩阵
 *b[N], c[N], e[N], f[N]: 一维布尔数组，用作标记数组或状态记录
 *
 *使用gets(s)读取换行符，避免影响后续输入
 *将每个字符转换为布尔值存储在二维数组a中('1'转为true，其他转为false)
 *
*外层循环从1到n-1，内层循环处理对角线以下的元素
这个双重循环主要处理矩阵中除主对角线外的所有元素
*检查反对角线平行线上的元素是否满足条件
^ 是异或运算符，当结果为真时执行操作
如果条件满足，则增加计数器k，并翻转数组b和c中的相应位
*类似地检查另一方向的反对角线平行线
条件满足时同样增加计数器并翻转数组e和f中的位
*处理主对角线上的所有元素
计算每个对角线元素与对应状态数组的异或结果，并累加到k中
 *
*矩阵索引:
[0,0] [0,1] [0,2] [0,3] [0,4]
[1,0] [1,1] [1,2] [1,3] [1,4]
[2,0] [2,1] [2,2] [2,3] [2,4]
[3,0] [3,1] [3,2] [3,3] [3,4]
[4,0] [4,1] [4,2] [4,3] [4,4]
 *
*i=1:           [4,0]
i=2:        [3,0] [4,1]
i=3:     [2,0] [3,1] [4,2]
i=4:  [1,0] [2,1] [3,2] [4,3]
 *
*i=1:           [0,4]
i=2:        [0,3] [1,4]
i=3:     [0,2] [1,3] [2,4]
i=4:  [0,1] [1,2] [2,3] [3,4]
 *
 *
 *行状态记录: 记录第 (n - i + j) 行是否已经进行了某种操作
 *列状态记录: 记录第 j 列是否已经进行了某种操作
 *
 */
#include <cstdio>
using namespace std;

const int N = 2048;
int n, k;
char s[N];
bool a[N][N], b[N], c[N], e[N], f[N];

int main() {
    scanf("%d",&n); gets(s);
    for (int i = 0; i < n; ++i) {
        gets(s);
        for (int j = 0; j < n; ++j) a[i][j] = s[j] == '1';
    }
    for (int i = 1; i < n; ++i) {
        for (int j = 0; j < i; ++j) {
            if (a[n - i + j][j] ^ b[n - i + j] ^ c[j]) {
                ++k;
                b[n - i + j] ^= 1;
                c[j] ^= 1;
            }
            if (a[j][n - i + j] ^ e[n - i + j] ^ f[j]) {
                ++k;
                e[n - i + j] ^= 1;
                f[j] ^= 1;
            }
        }
    }
    for (int i = 0; i < n; ++i) k += a[i][i] ^ b[i] ^ c[i] ^ e[i] ^ f[i];
    printf("%d\n", k);
    return 0;
}